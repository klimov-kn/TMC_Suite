// Язык интерфейса программ TMC Suite: русский или английский.
//
// Выбор хранится в %APPDATA%\TMC_Suite_Qt\Common.ini, [UI] Language = system | ru | en,
// и общий для всех программ пакета. «system» — по языку Windows (русский — если система
// русская, иначе английский), как в Android-версии.
//
// Перевод — по словарю resources/i18n/ui_strings.tsv (пары «английский — русский»):
// фильтр событий приложения при показе каждого окна и меню заменяет тексты, которые
// есть в словаре (надписи, кнопки, заголовки, пункты меню, подсказки). Поэтому меню и
// диалоги из .rc и новые окна переводятся без правки их кода. Строки, которые код
// собирает сам (с числами и именами файлов), берите через tmci18n::tr(ru, en).
/// @file tmci18n.h
/// @brief Язык интерфейса (русский/английский): словарь, перевод окон при показе, выбор языка.
///
/// Часть модуля «Общий слой интерфейса», отдельная библиотека `tmc_i18n` (её
/// берут все программы, включая FieldView и TPL Designer). Только поток интерфейса.
/// @see https://www.tamic.ru/docs/code/gui-common.html#i18n
#pragma once

#include <QString>

class QAction;
class QMenu;
class QWidget;

/// @brief Перевод интерфейса программ пакета.
namespace tmci18n {

/// Выбор языка: по системе, русский, английский.
enum class Lang { System, Ru, En };

/// @brief Читает выбор языка из `TMC_Suite_Qt/Common.ini` (`[UI] Language`).
/// @return `System` по умолчанию.
Lang setting();               // выбор человека (System по умолчанию)
/// @brief Записывает выбор языка и, если действующий язык изменился, переводит все открытые окна.
/// @param[in] lang  выбор
void setSetting(Lang lang);   // записать выбор и сразу перевести открытые окна
/// @brief Возвращает true, если действующий язык — русский.
/// @return true — интерфейс на русском; false — на английском.
bool russian();               // действующий язык — русский?

// Подключить словарь и фильтр событий (один раз, после создания QApplication).
/// @brief Загружает словарь, определяет язык, ставит перевод Qt и фильтр событий приложения (один раз).
/// @pre `QApplication` создан.
void install();

// Строка на действующем языке (для текста, который код собирает сам).
/// @brief Возвращает строку на действующем языке.
/// @param[in] ru  русский текст (UTF-8)
/// @param[in] en  английский текст (UTF-8)
/// @return Строка `ru` или `en` (из UTF-8) по действующему языку.
QString tr(const char *ru, const char *en);

// Перевести по словарю одну строку / все тексты окна (обычно делает фильтр сам).
/// @brief Переводит строку по словарю (точное совпадение, без «&», пункт с `\t`, шаблон со вставками).
/// @param[in] text  исходный текст
/// @return Перевод или исходный текст, если перевода нет или `install` не вызван.
QString translate(const QString &text);
/// @brief Переводит тексты окна и всех его дочерних виджетов и действий.
/// @param[in] w  окно; NULL — ничего
void translateWidget(QWidget *w);

// Свой перевод пункта меню (когда тот же английский текст в другом месте значит иное).
/// @brief Задаёт пункту меню собственную пару текстов, минуя словарь.
/// @param[in] act  пункт (не NULL)
/// @param[in] ru   русский текст (UTF-8)
/// @param[in] en   английский текст (UTF-8)
void setOwnText(QAction *act, const char *ru, const char *en);

// Подменю «Язык / Language» (Системный / Русский / English) — в меню настроек.
/// @brief Добавляет подменю выбора языка (не переводится).
/// @param[in] parent  меню-родитель (не NULL)
/// @return Созданное подменю.
QMenu *addLanguageMenu(QMenu *parent);

} // namespace tmci18n
