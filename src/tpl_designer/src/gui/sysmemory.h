/// @file sysmemory.h
/// @brief Объём физической памяти компьютера и доступная её часть (для кольцевой диаграммы памяти).
///
/// Часть модуля «Редактор заданий TPL Designer», слой интерфейса. Величины только
/// показываются рядом с оценкой памяти задания (`tpl::ramEstimate`) и в файл не попадают.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#gui-memory
#pragma once

// Сколько оперативной памяти у ЭТОГО компьютера и сколько из неё свободно.
//
// ⚠️ Единственное место в src/gui с ветками по системам — и иначе нельзя: Qt такой
// величины не даёт, а у каждой системы она своя (GlobalMemoryStatusEx, /proc/meminfo,
// sysctl + host_statistics64). Поведение программы от ветки не зависит: величина только
// рисуется на диаграмме памяти и в файл задания не попадает никак.

/// @brief Сведения о памяти этого компьютера, запрашиваемые у операционной системы.
namespace sysmem {

/// @brief Итог запроса памяти: удалось ли узнать, всего и доступно, байт.
struct Info {
    bool ok = false;        ///< удалось ли узнать
    double total = 0.0;     ///< байт физической памяти всего
    double available = 0.0; ///< байт можно занять, не выталкивая других на диск

    /// @brief Возвращает занятую часть памяти.
    /// @return `total - available`, байт (0, если `ok == false`).
    double used() const { return total - available; }
};

/// @brief Запрашивает у системы объём физической памяти и доступную часть.
///
/// Windows — `GlobalMemoryStatusEx` (та же функция, по которой ядро решает, копить ли ДН
/// по краям); macOS — `sysctl hw.memsize` и `host_statistics64` (свободные, неактивные,
/// сбрасываемые и спекулятивные страницы); Linux — `MemTotal`/`MemAvailable` из `/proc/meminfo`.
/// @return Сведения; `ok == false`, если система не ответила. `available` не больше `total`.
Info query();

} // namespace sysmem
