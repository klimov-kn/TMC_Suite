/// @file settings.h
/// @brief Настройки вида и поведения редактора, переживающие перезапуск (`settings::values`).
///
/// Часть модуля «Редактор заданий TPL Designer», слой интерфейса. Хранилище — INI-файл
/// `%APPDATA%/TMC_Suite_Qt/TPL Designer.ini` на Windows, `QSettings("TMC", "TplDesigner")`
/// на Linux и macOS. На содержимое `.tpl` настройки не влияют.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#gui-settings
#pragma once

#include <QColor>
#include <QString>

/// Настройки программы — то, что переживает перезапуск.
///
/// Здесь живут только предпочтения ВИДА и поведения редактора. Ничего, что влияет на
/// содержимое `.tpl`, тут быть не должно: файл задания обязан зависеть от того, что
/// пользователь нарисовал и ввёл, а не от того, какие галочки у него стоят в
/// настройках. Иначе «у меня считается, а у него нет» станет обычным делом.
/// @brief Настройки редактора: палитра eps, сетка, привязка, размеры, подтверждение перезаписи.
namespace settings {

/// Палитра градиентной заливки eps.
///
/// Viridis по умолчанию не из моды: он перцептивно равномерный (равный шаг значения =
/// равный шаг видимой яркости) и различим при дальтонизме. «Радуга» этим свойством не
/// обладает и рисует полосы там, где в данных ничего не меняется.
/// @brief Палитра заливки профиля eps на холсте.
enum class Palette {
    Viridis, ///< тёмно-синий -> бирюзовый -> жёлтый
    Heat,    ///< чёрный -> красный -> жёлтый -> белый
    Gray     ///< оттенки серого: для печати
};

/// @brief Возвращает название палитры для списка в окне настроек на действующем языке.
/// @param[in] p  палитра.
/// @return Название («Viridis (равномерная)», «Тепловая», «Серая»); пустая строка для неизвестного значения.
QString paletteName(Palette p);

/// Цвет по нормированному значению t из [0,1]. Вне диапазона зажимается.
/// @brief Вычисляет цвет палитры линейной интерполяцией между опорными точками.
/// @param[in] p  палитра.
/// @param[in] t  нормированное значение, безразмерное; ожидается [0, 1], вне — зажимается.
/// @return Цвет; для неизвестной палитры — чёрный.
QColor paletteColor(Palette p, double t);

/// @brief Набор значений настроек; значения по умолчанию — при первом запуске.
struct Values {
    // --- профиль eps ---
    bool epsColorBar = true;   ///< вертикальная шкала значений у края холста
    bool epsTooltip = true;    ///< значение eps под курсором
    bool epsGradient = true;   ///< градиентная заливка (иначе ровная, как у обычной eps)
    /// Палитра градиентной заливки eps.
    Palette palette = Palette::Viridis;

    // --- холст ---
    /// Показывать точки сетки на холсте.
    bool gridVisible = true;
    /// Привязка к узлам сетки при рисовании и перетаскивании.
    bool snapEnabled = true;
    bool showDimensions = true; ///< размеры выделенной фигуры прямо на холсте

    // --- поведение ---
    bool confirmOverwrite = true; ///< спрашивать перед записью поверх существующего .tpl
};

/// Текущие значения. Читаются из QSettings при первом обращении.
/// @brief Возвращает текущие настройки (при первом обращении читает их из хранилища).
/// @return Ссылка на значения, общие для процесса; действительна до выхода из программы.
const Values &values();

/// Заменить и немедленно записать в QSettings.
/// @brief Заменяет настройки процесса и сразу записывает их в хранилище.
/// @param[in] v  новые значения; записываются в группы `view` и `behaviour`.
void setValues(const Values &v);

/// Где лежат настройки. Windows: один INI вместе с остальными программами пакета —
/// `%APPDATA%\TMC_Suite_Qt\TPL Designer.ini` (раньше — два разных ключа реестра
/// `HKCU\Software\TMC\TplDesigner` и `…\TMC\TPL Designer`, их перенос — однократно).
/// Вызвать в main после создания QApplication: после этого и QSettings() без доводов
/// пишет в тот же файл. На Linux и macOS ничего не меняет.
/// @brief Направляет `QSettings` по умолчанию в общий INI пакета и однократно переносит старые ключи реестра.
void installStorage();

} // namespace settings
