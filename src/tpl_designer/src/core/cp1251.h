/// @file cp1251.h
/// @brief Кодировка CP1251 файлов задания: своя таблица, чтение с автоопределением, запись CRLF.
///
/// Часть ядра TPL Designer. Все файлы для ядер (`.tpl`, `_step.h`, `.sig`, пакетные
/// файлы) пишутся через `writeCp1251File`; задания читаются через `readTplFileText`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#encoding
#pragma once

#include <QByteArray>
#include <QString>

namespace tpl {

/// Кодирует строку в CP1251 — кодировку, которую ждут ядра TMC Suite.
///
/// Qt для этого использовать нельзя: QStringEncoder("windows-1251") молча возвращает
/// пустой QByteArray (QStringConverter знает только UTF-8/16/32 и ISO-8859-1).
/// Системный кодировщик — тоже нельзя, и не только потому, что WideCharToMultiByte
/// есть лишь на Windows: файл задания обязан получаться ОДИНАКОВЫМ на Windows, macOS
/// и Linux, а это гарантирует только своя таблица (она в cp1251.cpp).
///
/// Символы, которых нет в CP1251, заменяются на '?', а \p lossy (если передан)
/// выставляется в true. Подстановка «похожего» символа (best-fit) отключена намеренно:
/// иначе '→' молча превратился бы в '>', а '№' в 'N'.
/// @brief Перекодирует строку Unicode в байты CP1251 по собственной таблице.
/// @param[in]  s      исходный текст.
/// @param[out] lossy  если не `nullptr` — true, когда хотя бы один символ заменён на '?'.
/// @return Байты CP1251 той же длины в символах (пара суррогатов -> один '?'); пустой массив для пустой строки.
QByteArray toCp1251(const QString &s, bool *lossy = nullptr);

/// Декодирует байты из CP1251 в строку — обратное к \ref toCp1251.
///
/// Qt здесь так же бесполезен: QStringDecoder("windows-1251") невалиден, поэтому
/// работаем по той же таблице. Байту 0x98, которому в CP1251 не сопоставлен символ,
/// отдаём U+FFFD (так же поступает Windows) — потерей это не считаем:
/// файл всё равно надо показать пользователю, а не молча отвергнуть.
/// @brief Декодирует байты CP1251 в строку Unicode.
/// @param[in] bytes  байты в CP1251.
/// @return Строка той же длины; байт 0x98 -> U+FFFD.
QString fromCp1251(const QByteArray &bytes);

/// Декодирует содержимое файла задания, САМ определяя кодировку.
///
/// Наши файлы всегда CP1251, но задание могли написать в блокноте с UTF-8.
/// Правило: BOM -> UTF-8; иначе текст, целиком проходящий проверку UTF-8 и
/// содержащий хотя бы один байт >= 0x80, считаем UTF-8; всё остальное — CP1251.
/// Чистый ASCII в обеих кодировках один и тот же, так что выбор на нём не важен.
/// \p wasUtf8 (если передан) сообщает, какая ветка сработала.
/// @brief Декодирует байты файла задания, выбирая между UTF-8 и CP1251.
/// @param[in]  bytes    содержимое файла.
/// @param[out] wasUtf8  если не `nullptr` — true, когда текст разобран как UTF-8 (по BOM или проверке).
/// @return Декодированный текст (переводы строк не меняются).
QString decodeTplBytes(const QByteArray &bytes, bool *wasUtf8 = nullptr);

/// Читает файл задания (или включаемый .h) с автоопределением кодировки.
/// Возвращает false, если файл не открылся; текст нормализуется к переводам '\n'.
/// @brief Читает текстовый файл задания с автоопределением кодировки.
/// @param[in]  path     путь к файлу.
/// @param[out] text     если не `nullptr` — текст с переводами строк LF.
/// @param[out] error    если не `nullptr` — причина отказа (по-русски).
/// @param[out] wasUtf8  если не `nullptr` — true, когда файл был в UTF-8.
/// @return true — файл прочитан; false — не открылся.
bool readTplFileText(const QString &path, QString *text, QString *error = nullptr,
                     bool *wasUtf8 = nullptr);

/// Пишет текст в файл в CP1251 с переводами строк `\r\n` (как в эталонах samples/TEST).
///
/// ⚠ CRLF ставится НА ЛЮБОЙ системе, а не «как принято в этой». Задание, сделанное
/// на macOS, обязано быть тем же файлом, что и сделанное на Windows: ядра читают
/// строку до перевода и лишний CR отбрасывают, поэтому CRLF безопасен везде, а вот
/// одинокий LF в windows-сборках пакета читается не всегда.
///
/// Возвращает false, если файл не открылся или записался не полностью.
/// \p lossy (если передан) сообщает, что часть символов заменена на '?' — повод
/// предупредить пользователя, а не тихо отдать ядру испорченный комментарий.
/// @brief Записывает текст в файл в CP1251 с переводами строк CRLF (атомарно, через `QSaveFile`).
/// @param[in]  path   путь к файлу (перезаписывается).
/// @param[in]  text   текст; переводы строк любые, приводятся к CRLF.
/// @param[out] error  если не `nullptr` — причина отказа.
/// @param[out] lossy  если не `nullptr` — true, когда часть символов заменена на '?'.
/// @return true — файл записан целиком; false — ошибка открытия, записи или фиксации.
bool writeCp1251File(const QString &path, const QString &text,
                     QString *error = nullptr, bool *lossy = nullptr);

} // namespace tpl
