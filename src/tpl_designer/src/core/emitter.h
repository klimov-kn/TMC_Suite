/// @file emitter.h
/// @brief Эмиттер и проверка задания: `validate`, моно-версия `.tpl`, макро-версия с
///        `<имя>_step.h`, конвейер заданий по частотам, запись чисел без экспоненты.
///
/// Часть ядра редактора заданий. Все функции чистые: получают `Project` и возвращают
/// текст в Unicode; на диск его пишет `writeTask` (CP1251, CRLF).
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#emitter
#pragma once

#include "project.h"

#include <QString>
#include <QStringList>

namespace tpl {

/// Метка служебной строки углового свипа в шапке задания. По ней чтение
/// восстанавливает свип (см. `sweepHeader` в emitter.cpp).
inline constexpr const char *kSweepMarker = "@TPLD-SWEEP";

/// Макро-версия задания: файлы обязаны лежать рядом.
struct MacroFiles {
    QString tpl;       ///< содержимое `<name>.tpl`
    QString stepH;     ///< содержимое `<name>_step.h`
    QString stepHName; ///< имя .h для строки `#include`
};

/// @brief Итог проверки задания: ошибки (запись запрещена) и предупреждения.
///
/// Ошибка — только то, что ядро отвергнет или молча посчитает не то, что нарисовано;
/// всё остальное — предупреждение. Тексты — на текущем языке интерфейса.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#validate
struct Diagnostics {
    /// Файл писать нельзя: ядро не примет или молча посчитает не то.
    QStringList errors;

    /// Файл корректен, но что-то стоит знать. Решает пользователь — не запрещаем.
    QStringList warnings;

    /// @brief Сообщает, можно ли писать файл.
    /// @return true — ошибок нет (предупреждения допустимы).
    bool ok() const { return errors.isEmpty(); }
};

/// @brief Проверяет задание по правилам языка `.tpl` и ограничениям ядер до записи файла.
///
/// Проверяет имя и частоты, шаг и область, потолки пакета (99 частот на задание,
/// 20 входов), имена выходных файлов, номера блоков, геометрию фигур, плазму и профиль
/// eps, порты (eps входа > 0, плоскость внутри области и в своей половине, окно
/// пассивного порта, сигнал из файла), конвейер, варианты, угловой свип, размещение
/// на сетке (`checkPlacement`) и символы описания вне CP1251.
/// @param[in] p  задание
/// @return Ошибки и предупреждения; `ok()` — файл можно писать.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#validate
Diagnostics validate(const Project &p);

/// Одна частота — один `#STEP`.
/// @param[in] p  задание (при действующем угловом свипе — свип явными шагами)
/// @return Полный текст `.tpl`: шапка, шаги по сочетаниям «вариант x возбуждение»
///         и частотам, `#EOF`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#emitter
QString emitMono(const Project &p);

/// Диапазон частот — макрос: шаг описан ОДИН раз, число шагов = числу строк вызова.
///
/// Если поля просят только на первом шаге, первый шаг пишется явно, а остальные —
/// вызовами: тело макроса одно на все частоты, «первого» внутри него не существует.
/// @param[in] p  задание (при действующем угловом свипе — свип макросом по углу)
/// @return Тексты `<имя>.tpl` и `<имя>_step.h` и имя включаемого файла.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#macro
MacroFiles emitMacro(const Project &p);

/// Больше одной частоты — макрос. Две частоты уже повод не плодить копипасту.
/// @param[in] p  задание
/// @return true — частот больше одной или действует угловой свип.
bool needsMacro(const Project &p);

/// Одно задание конвейера: своя часть сетки частот и свои выходные файлы.
struct TaskChunk {
    QString name;          ///< имя задания без расширения: `wg_001`
    QString tpl;           ///< содержимое .tpl
    QString stepH;         ///< содержимое _step.h; пусто — моно-версия
    QString stepHName;     ///< имя .h для строки `#include`
    QVector<double> freqs; ///< частоты именно этого задания
    /// Файлы `.s` этого задания, без расширения. Их удаляют ПЕРЕД прогоном: ядро
    /// дописывает матрицу, а не перезаписывает.
    QStringList sMatrixFiles;
};

/// Разложить сетку частот по файлам задания.
///
/// Без конвейера возвращает ОДИН элемент — то же самое задание. Поэтому вызывающему
/// не нужно ветвление «делим или нет»: путь всегда один.
///
/// Каждому заданию дают СВОИ имена выходных файлов: иначе `.s` (он дописывается, а не
/// перезаписывается) перемешал бы точки разных заданий, а при запуске пачкой — ещё и
/// испортился бы от одновременной записи. Файл падающей волны, наоборот, ОБЩИЙ: он
/// один и тот же для всех частей, и плодить сотню копий незачем.
/// @param[in] p  задание
/// @return Задания конвейера `<имя>_001` ... (ширина номера — по числу частей); без
///         конвейера — одно задание с исходным именем.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#chunks
QVector<TaskChunk> emitChunks(const Project &p);

/// Выражение для параметра Amp блока INPUT_*.
///
/// Ядро считает a = Amp(t,f)*sin(2*pi*FREQ*t + Faza(t,f)) и режет резким окном.
/// Amp — не число, а выражение от t (нс) и f (ГГц): огибающая живёт здесь.
/// Интерпретатор понимает abs/exp/log/sin/cos/tan/sqrt/sinh/cosh/tanh/asin/acos/atan/log10
/// (строчными, со скобкой) и степень '^'.
/// @param[in] s  сигнал (используются `shape`, `amplitude`, `center`, `duration`)
/// @return Выражение Amp: число для непрерывного и прямоугольного сигнала,
///         `amp*exp(-x*x)` с `x = ((t-t0)/tau)` для гауссова (квадрат умножением,
///         не через `^`).
/// @see https://www.tamic.ru/docs/theory/ports.html#signal
QString ampExpression(const Signal &s);

/// Окно возбуждения порта, нс. У пассивного начинается заведомо позже конца счёта.
/// @param[in] p        порт
/// @param[in] timeMax  конец счёта, нс
/// @return Окно, нс: пассивный порт — [2*timeMax; 3*timeMax]; сигнал из файла — опора
///         сигнала, обрезанная концом счёта; непрерывный и гауссов — [0; timeMax];
///         прямоугольный — center -+ duration/2.
TimeWindow portWindow(const Port &p, double timeMax);

/// 60 -> "60.0", 0.071 -> "0.071", 3.1e17 -> "310000000000000000.0".
/// Экспоненты не бывает НИКОГДА: вычислитель выражений ядра её не понимает.
/// @param[in] v  число
/// @return Запись до 10 значащих цифр, всегда с десятичной точкой.
QString formatNumber(double v);
/// "3.1e+17" -> "310000000000000000", "1.5e-05" -> "0.000015"; без экспоненты — как есть.
/// @param[in] number  запись числа (возможно, с экспонентой)
/// @return Та же величина полной десятичной записью без лишних нулей.
QString plainDecimal(const QString &number);
/// Все числа с экспонентой в выражении — полной десятичной записью.
/// @param[in] expr  выражение пользователя
/// @return Выражение, где числа с экспонентой (не прилипшие к именам) заменены
///         полной записью с точкой.
QString plainLiterals(const QString &expr);
/// Без хвостовой ".0": 115 -> "115".
/// @param[in] v  число
/// @return Запись до 10 значащих цифр без экспоненты и без хвостовой точки.
QString formatCompact(double v);
/// FREQ — всегда один знак после точки.
/// @param[in] ghz  частота, ГГц
/// @return Один знак после точки, если частота кратна 0.1 ГГц; иначе столько знаков,
///         сколько нужно (округление до 1e-9 ГГц).
QString formatFreq(double ghz);

} // namespace tpl
