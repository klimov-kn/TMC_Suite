/// @file rf.h
/// @brief Формулы паспортов образцов: волноводы, неоднородности, фильтры, микрополоска, ЭПР.
///
/// Часть модуля «Ядро TPL Designer», каталог образцов. Используется рецептами для
/// строк «теория» в паспорте и для подбора размеров по заданным характеристикам.
/// Реализация — `rf.cpp`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#samples
#pragma once

#include <QVector>

#include <complex>

/// Формулы паспортов образцов: волновод, неоднородности, микрополоска, фильтры,
/// рупор, рассеяние на цилиндре. Единицы — как в редакторе: мм и ГГц.
///
/// Это ТЕОРИЯ для сравнения с тем, что посчитает ядро, а не замена ему: там, где
/// формула приближённая, в паспорте так и написано.
namespace tpl::samples::rf {

/// Комплексное число двойной точности.
using cplx = std::complex<double>;

/// Число pi.
constexpr double kPi = 3.14159265358979323846;
/// Импеданс свободного пространства, Ом.
constexpr double kEta0 = 376.730313668;

/// Длина волны в свободном пространстве, мм.
/// @param[in] fGHz  частота, ГГц (> 0)
/// @return Длина волны, мм.
double lambda0(double fGHz);

/// Длина волны H10 в волноводе шириной a, мм. 0 — ниже отсечки.
/// @param[in] aMm   ширина широкой стенки, мм
/// @param[in] fGHz  частота, ГГц
/// @param[in] eps   относительная проницаемость заполнения
/// @return Длина волны в волноводе, мм; 0 — волна не распространяется.
double lambdaGuide(double aMm, double fGHz, double eps = 1.0);

/// Тонкая симметричная индуктивная диафрагма с окном d в волноводе a (Маркувиц,
/// приближение тонкой диафрагмы): нормированная реактивная проводимость B/Y0 < 0.
/// @param[in] aMm   ширина волновода, мм
/// @param[in] dMm   ширина окна диафрагмы, мм
/// @param[in] fGHz  частота, ГГц (выше отсечки H10)
/// @return B/Y0 (безразмерная, отрицательная).
double irisSusceptance(double aMm, double dMm, double fGHz);

/// Окно d, дающее нормированную реактивность X = |1/B| (обратная задача).
/// @param[in] aMm   ширина волновода, мм
/// @param[in] x     нормированная реактивность X/Z0 (отрицательная считается нулём)
/// @param[in] fGHz  частота, ГГц
/// @return Ширина окна, мм.
double irisWindowForReactance(double aMm, double x, double fGHz);

/// Тонкий центральный индуктивный штырь диаметром d (Маркувиц): нормированная
/// реактивность шунта X/Z0.
/// @param[in] aMm   ширина волновода, мм
/// @param[in] dMm   диаметр штыря, мм
/// @param[in] fGHz  частота, ГГц
/// @return X/Z0 (безразмерная); ряд суммируется по нечётным n до 4000.
double postReactance(double aMm, double dMm, double fGHz);

/// Модуль отражения от шунтирующей реактивной проводимости jB в согласованной линии.
/// @param[in] b  нормированная проводимость B/Y0
/// @return |Г| = |b|/sqrt(4+b^2).
double shuntReflection(double b);

/// Коэффициент отражения от слоя толщиной d с проницаемостью eps (может быть
/// отрицательной — плазма) в волноводе шириной a для волны H10; a <= 0 — свободное
/// пространство, нормальное падение. Точная формула однородного слоя.
/// @param[in] aMm   ширина волновода, мм; <= 0 — свободное пространство
/// @param[in] eps   комплексная относительная проницаемость слоя
/// @param[in] dMm   толщина слоя, мм
/// @param[in] fGHz  частота, ГГц
/// @return Комплексный коэффициент отражения на передней грани слоя.
cplx slabReflection(double aMm, cplx eps, double dMm, double fGHz);

/// Прототип фильтра нижних частот: g0...g(n+1).
/// @param[in] n  порядок фильтра (>= 1)
/// @return Вектор длины n+2: g0 = 1, g1...gn — элементы Баттерворта, g(n+1) = 1.
QVector<double> butterworth(int n);
/// @brief Возвращает g-параметры прототипа Чебышёва g0...g(n+1).
/// @param[in] n         порядок фильтра (>= 1)
/// @param[in] rippleDb  неравномерность в полосе пропускания, дБ
/// @return Вектор длины n+2; g(n+1) = 1 при нечётном n.
QVector<double> chebyshev(int n, double rippleDb);

// --- микрополоска (Хаммерстад, Йенсен; квазистатика) ---
/// @brief Возвращает эффективную проницаемость микрополосковой линии (квазистатика).
/// @param[in] u   отношение ширины полоски к толщине подложки w/h
/// @param[in] er  относительная проницаемость подложки
/// @return eps_eff (безразмерная).
double msEpsEff(double u, double er);      ///< u = w/h
/// @brief Возвращает волновое сопротивление микрополосковой линии (квазистатика).
/// @param[in] u   отношение w/h
/// @param[in] er  относительная проницаемость подложки
/// @return Z0, Ом.
double msZ0(double u, double er);          ///< Ом
/// @brief Подбирает отношение w/h под заданное волновое сопротивление.
///
/// Начальное приближение — формулы синтеза, затем до 30 шагов уточнения по `msZ0`.
/// @param[in] z0  требуемое сопротивление, Ом
/// @param[in] er  относительная проницаемость подложки
/// @return Отношение w/h.
double msWidthRatio(double z0, double er); ///< синтез: w/h для заданного Z0
/// Ширина планарной волноводной модели: полоска заменена волноводом ширины W_eff с
/// магнитными стенками и заполнением eps_eff. W_eff = eta0*h/(Z0*sqrt(eps_eff)), мм.
/// @param[in] z0      волновое сопротивление линии, Ом
/// @param[in] epsEff  эффективная проницаемость
/// @param[in] hMm     толщина подложки, мм
/// @return Ширина канала планарной модели, мм.
double msPlanarWidth(double z0, double epsEff, double hMm);

// --- рассеяние ---
/// @brief Вычисляет функцию Бесселя первого рода J_n(x) интегралом Бесселя (Симпсон).
/// @param[in] n  порядок (целый)
/// @param[in] x  аргумент
/// @return J_n(x).
double besselJ(int n, double x);
/// @brief Вычисляет функцию Бесселя второго рода Y_n(x) интегральным представлением.
/// @param[in] n  порядок (целый)
/// @param[in] x  аргумент (> 0)
/// @return Y_n(x).
double besselY(int n, double x);
/// Погонная моностатическая ЭПР идеально проводящего цилиндра радиуса a, мм.
/// tm = true — E вдоль оси цилиндра.
/// @param[in] aMm   радиус цилиндра, мм
/// @param[in] fGHz  частота, ГГц
/// @param[in] tm    true — поляризация TM (E вдоль оси), false — TE
/// @return Погонная ЭПР (ширина рассеяния), мм.
double cylinderEchoWidth(double aMm, double fGHz, bool tm);
/// Погонная ЭПР полосы шириной w (физическая оптика), E вдоль полосы; phi — угол
/// между направлением падения и плоскостью полосы, градусы. мм.
/// @param[in] wMm     ширина полосы, мм
/// @param[in] fGHz    частота, ГГц
/// @param[in] phiDeg  угол между направлением падения и плоскостью полосы, градусы
/// @return Погонная ЭПР, мм.
double stripEchoWidth(double wMm, double fGHz, double phiDeg);

/// Децибелы от модуля.
/// @param[in] mag  модуль (безразмерный); ниже 1e-12 считается равным 1e-12
/// @return 20*lg(mag), дБ.
double dB(double mag);

} // namespace tpl::samples::rf
