/// @file standards.h
/// @brief Справочные таблицы каталога образцов: стандартные сечения волноводов и СВЧ-подложки.
///
/// Часть модуля «Ядро TPL Designer», каталог образцов. Номер строки таблицы служит
/// значением параметра-выбора образца. Реализация — `standards.cpp`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#samples
#pragma once

#include <QString>
#include <QStringList>
#include <QVector>

/// Справочные таблицы библиотеки образцов: сечения волноводов и СВЧ-подложки.
namespace tpl::samples {

/// Прямоугольный волновод стандартного сечения.
///
/// ⚠️ Ядро двумерное и считает H-плоскость: в расчёт входит только широкая стенка `a`.
/// Узкая `b` — справка из стандарта, на задание она не влияет.
struct WaveguideStd {
    QString name;     ///< «WR-90 / R100» или «ГОСТ 23x10»
    QString family;   ///< «EIA / IEC» или «ГОСТ 20900-75»
    double a = 0.0;   ///< широкая стенка, мм
    double b = 0.0;   ///< узкая стенка, мм (справка)
    double fLo = 0.0; ///< рабочий диапазон, ГГц
    /// Верхняя граница рабочего диапазона, ГГц.
    double fHi = 0.0;
    bool bandFromStandard = false; ///< диапазон из стандарта, а не расчётный 1.25..1.9 fc

    /// @brief Возвращает частоту отсечки H10 пустого волновода: c/(2a).
    /// @return Частота, ГГц.
    double fc10() const;          ///< отсечка H10, ГГц
    /// @brief Возвращает строку выпадающего списка: имя, сечение, диапазон, пометка «расч.».
    /// @return Строка на текущем языке.
    QString label() const;        ///< строка выпадающего списка
};

/// @brief Возвращает таблицу сечений: серия EIA/IEC, затем основная серия ГОСТ 20900-75.
/// @return Ссылка на статическую таблицу (своя на каждый язык, порядок и числа одинаковые).
const QVector<WaveguideStd> &waveguides();
/// @brief Возвращает строки выпадающего списка сечений в порядке `waveguides()`.
/// @return Список подписей `WaveguideStd::label()`.
QStringList waveguideChoices();
/// Номер WR-90 в таблице — умолчание для большинства образцов (X-диапазон, 8.2-12.4 ГГц).
/// @return Номер строки WR-90 в `waveguides()`; 0, если не найдена.
int defaultWaveguide();
/// Номер ближайшего стандарта, в полосе которого лежит частота.
///
/// Перебираются только сечения EIA/IEC (диапазон из стандарта). Если частота не попала
/// ни в одну полосу — берётся ближайшее по середине полосы сечение, где частота лежит
/// между 1.1*fc10 и 1.95*fc10; не нашлось и такого — `defaultWaveguide()`.
/// @param[in] fGHz  частота, ГГц
/// @return Номер строки в `waveguides()`.
int waveguideForFreq(double fGHz);

/// Подложка для микрополосковых образцов.
struct Substrate {
    /// Название материала («FR-4», «Rogers RO4003C»).
    QString name;
    double eps = 1.0;  ///< относительная проницаемость
    double h = 1.0;    ///< стандартная толщина, мм
    QString note;      ///< откуда число
};

/// @brief Возвращает таблицу подложек.
/// @return Ссылка на статическую таблицу (своя на каждый язык).
const QVector<Substrate> &substrates();
/// @brief Возвращает строки выпадающего списка подложек: «имя — eps, h».
/// @return Список подписей в порядке `substrates()`.
QStringList substrateChoices();

} // namespace tpl::samples
