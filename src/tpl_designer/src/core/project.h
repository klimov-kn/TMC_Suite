bool isConvex(const QVector<QPointF> &pts);

/// @brief Возвращает название материала для интерфейса и комментариев задания.
/// @param[in] m  материал
/// @return Название на текущем языке («металл», «магнитная стенка», ...).
QString materialName(Material m);

/// Куда смотрит порт. Левая/правая — это INPUT_X, верхняя/нижняя — INPUT_Y.
///
/// ⚠️ Это НЕ «на какой границе стоит вход». Ядро ставит узлы входа ровно по той
/// координате, которая записана в `#LINK_LIST` (`TmcRTHNodeDiel.cpp: SetInpXLeft`
/// берёт `GetX0()` буквально), а «левый/правый» выводит из того, в какой ПОЛОВИНЕ
/// коробки эта координата лежит (`TmcRTH_IndanTopology.cpp:145-190`).
/// Поэтому вход можно поставить где угодно внутри счётной области — сторона задаёт
/// лишь направление, в котором пойдёт падающая волна.
enum class PortSide { Left, Right, Top, Bottom };

/// Апертура идёт вдоль оси Y (INPUT_X), а не вдоль X.
/// @param[in] s  сторона порта
/// @return true для левого и правого портов (`INPUT_X`), false для верхнего и нижнего.
bool portAlongY(PortSide s);

/// Тип возбуждаемой моды — пространственное распределение поля в апертуре.
/// ⚠️ Формы сигнала во времени НЕ задаёт (частая ошибка): она в Amp/Faza.
enum class PortMode {
    H10,     ///< METAL или пусто — волна H10
    Plane    ///< MAGNETIC — плоская волна
};

/// Форма сигнала во времени.
///
/// Ядро всегда излучает a = Amp(t,f)*sin(2pi*FREQ*t + Faza(t,f)) и режет резким окном
/// [tMin,tMax]. Amp — не число, а ВЫРАЖЕНИЕ от t и f, поэтому огибающую задаём им.
enum class SignalShape {
    Continuous, ///< несущая всё окно; Amp — константа
    Gaussian,   ///< гауссова огибающая: Amp = amp*exp(-((t-t0)/tau)^2)
    Rectangular ///< резко включить/выключить окном. Спектр «расползётся» — предупреждаем
};

/// Временное окно возбуждения, нс.
struct TimeWindow {
    /// Начало окна, нс.
    double tMin = 0.0;
    /// Конец окна, нс.
    double tMax = 0.0;

    /// @brief Возвращает длительность окна, нс.
    /// @return `tMax - tMin`, нс.
    double length() const { return tMax - tMin; }
};

/// Откуда ядро берёт падающую волну a(t) на этом порту.
///
/// 🔑 Две принципиально разные дороги, и выбор между ними — не вкус, а то, что
/// вообще выразимо. Ядро умеет считать только `a = Amp(t,f)*sin(2pi*FREQ*t + Faza)`:
/// несущую под огибающей. Пила, гребёнка тонов, ЛЧМ, видеоимпульс без несущей и
/// «любая форма, какую вздумается» в это произведение не укладываются НИКАК.
///
/// Поэтому в ядра пакета (правка 2026-09-30) добавлен второй путь: на месте `Amp`
/// пишется имя файла в квадратных скобках, и файл задаёт ВСЮ a(t) целиком —
/// `INPUT_X ; ylo; yhi; Tmin; Tmax; [wg_multi]; 0;`. Файл генератор пишет сам, так
/// что пользователь выбирает форму картинкой, а не считает точки руками.
enum class SignalSource {
    Formula, ///< Amp(t,f)*sin(...) — выражение считает само ядро
    File     ///< [имя] на месте Amp: файл .sig задаёт всю a(t)
};

/// Форма волны, которую генератор запишет в файл `.sig`.
///
/// Порядок здесь — это порядок картинок в галерее, от самого нужного к частному.
/// Первая форма и есть смысл всей затеи: гребёнка тонов считает сразу всю полосу
/// за ОДИН проход вместо свипа по частотам (выигрыш 7.8x на десяти частотах,
/// проверено прогоном 2026-09-30).
enum class Waveform {
    MultiTone,  ///< гребёнка равных тонов f1...f2 — вся полоса за один проход
    Chirp,      ///< ЛЧМ: несущая едет от f1 до f2 за длительность посылки
    SineBurst,  ///< N периодов синуса; при N = 1 это «моноимпульс»
    GaussRf,    ///< радиоимпульс: несущая под гауссовой огибающей
    GaussVideo, ///< видеоимпульс: гауссова шапка без несущей
    Monocycle,  ///< моноцикл (первая производная гаусса) — нулевое среднее
    Trapezoid,  ///< видеоимпульс с фронтами: фронт, полка, спад
    Sawtooth,   ///< пила
    Triangle,   ///< треугольник
    Square,     ///< меандр
    Expression, ///< произвольная формула a(t) — считаем МЫ, а не ядро
    Table       ///< произвольные точки: импорт двух колонок или чужой .sig
};

/// Параметры формы волны. Одна структура на все формы: поля, которых форма не
/// касается, просто не читаются — так галерея переключается, не теряя введённого.
struct Waveshape {
    /// Форма волны (выбор в галерее).
    Waveform kind = Waveform::MultiTone;

    /// Безразмерная! Единиц напряжения в языке задания НЕТ ни у Amp, ни в файле.
    double amplitude = 1.0;

    double start = 0.0;     ///< нс: когда сигнал начинается
    double duration = 40.0; ///< нс: сколько длится посылка (гребёнка, ЛЧМ, пила, формула)

    /// ГГц. У гребёнки и ЛЧМ — нижняя граница полосы; у синуса, радиоимпульса и
    /// моноцикла — несущая; у пилы, треугольника и меандра — частота ПОВТОРЕНИЯ.
    double f1 = 3.0;
    double f2 = 4.8; ///< ГГц: верхний тон гребёнки / конец ЛЧМ

    int tones = 10;   ///< тонов в гребёнке (не меньше двух)
    int periods = 1;  ///< периодов синуса в посылке

    double width = 0.2; ///< нс: tau гауссовой шапки и моноцикла
    double rise = 0.05; ///< нс: фронт трапеции
    double fall = 0.05; ///< нс: спад трапеции

    /// a(t) для Waveform::Expression. Переменная одна — `t` в нс. Считает наш
    /// tpl::ExprProgram, в файл уходят уже числа: ядру формулу отдавать нечем.
    QString expression;

    /// Таблица для Waveform::Table: x — время в нс, y — безразмерное a.
    QVector<QPointF> points;

    /// Тоны таблицы, ГГц — строка `#FREQ` из принесённого файла `.sig`.
    ///
    /// Раньше чужой многотон терял её при чтении: точки брались, а список тонов нет,
    /// и постобработке оставалось искать их по спектру — а это неточно (соседние линии
    /// смещают пики, см. \ref waveTones). Храним список ЦЕЛИКОМ, как в файле: обрезку
    /// до \ref kMaxFreqs делает запись, и о ней же говорит проверка.
    QVector<double> tableTones;
};

/// @brief Сигнал возбуждения порта: формула для ядра или файл падающей волны `.sig`.
///
/// При `source == Formula` эмиттер пишет `Amp` и `Faza` выражениями от t, f (форма —
/// `shape`); при `source == File` — `[имя]` на месте `Amp`, а сам файл строит
/// `sigfile.h` по `wave`.
/// @see https://www.tamic.ru/docs/theory/ports.html#signal
/// @see https://www.tamic.ru/docs/theory/ports.html#incident-file
struct Signal {
    /// Формулой или файлом. По умолчанию — как было: формулой.
    SignalSource source = SignalSource::Formula;

    SignalShape shape = SignalShape::Continuous; ///< при source == Formula
    double amplitude = 1.0; ///< безразмерная! Единицы напряжения в языке НЕТ
    double phase = 0.0;     ///< радианы

    // --- только для Gaussian ---
    double center = 0.0;   ///< t0, нс — центр импульса
    double duration = 1.0; ///< tau, нс — длительность (полуширина огибающей)

    /// При source == File: что записать в файл.
    Waveshape wave;

    /// Имя файла `.sig` без расширения. Пусто — генератор даст своё по имени порта.
    /// ⚠️ Точка в имени запрещена: расширение `.sig` ядро дописывает само, но
    /// только если точки в имени нет (`SeachSignalFileName`).
    QString file;
};

/// Порт = один BLOCK с INPUT_X/INPUT_Y + его строка в `#LINK_LIST`.
struct Port {
    /// Номер блока входа (`BLOCK`); общее пространство номеров с фигурами, id >= 1.
    int id = 0;
    /// Имя порта для легенды; в файл уходит комментарием.
    QString name;
    /// Направление падающей волны (`Left`/`Right` — `INPUT_X`, `Top`/`Bottom` — `INPUT_Y`).
    PortSide side = PortSide::Left;

    /// Апертура, мм: Y-диапазон для левого/правого входа, X — для верхнего/нижнего.
    double from = 0.0;
    /// Конец апертуры, мм (начало — `from`).
    double to = 0.0;

    /// Координата плоскости входа ПОПЕРЁК апертуры: x для левого/правого, y для
    /// нижнего/верхнего. Пусто — вход стоит на границе счётной области (обычный случай).
    ///
    /// Ядро берёт эту координату буквально, так что вход законно ставится и внутри
    /// области — например, в горловине рупора. Единственный запрет: за коробку нельзя.
    std::optional<double> plane;

    /// Возбуждается ли. Пассивный только принимает.
    ///
    /// Активных портов может быть сколько угодно — запрета нет ни в языке, ни здесь.
    /// Но при более чем одном активном .s перестаёт быть матрицей рассеяния:
    /// на каждом порту придёт сумма откликов, и разделить их из одного прогона нечем.
    /// Это законный расчёт (запитать решётку и посмотреть поле) — просто смотреть
    /// результат надо в полях и ДН. Предупреждает validate(), не запрещает.
    bool active = false;

    /// Мода входа: волна H10 (`METAL`) или плоская волна (`MAGNETIC`).
    PortMode mode = PortMode::H10;
    /// Сигнал возбуждения; у пассивного порта не используется.
    Signal signal;

    /// Диэлектрическая проницаемость среды В СЕЧЕНИИ ВХОДА. Влияет на волновую
    /// проводимость входа, а значит и на то, что попадёт в S-матрицу.
    ///
    /// ⚠️ Здесь хранится САМА eps, а в файл уходит ДОБАВКА (eps-1) — восьмым параметром
    /// блока INPUT_*. Ловушка ровно та же, что у диэлектрической фигуры: вакуум eps=1
    /// пишется как 0. Пользователь везде вводит саму eps, минус единицу ставит эмиттер.
    ///
    /// ⚠️ Ядро проверяет `(r + 1.0) <= 0.0` и отказывается грузить файл
    /// (`TmcRTH_BolckList.cpp`, разбор ReadInputX/ReadInputY). Поэтому eps строго > 0 —
    /// это ошибка валидатора, а не предупреждение.
    double eps = 1.0;

    /// Брать eps входа из среды, в которой он стоит, а не из \ref eps.
    ///
    /// 🔑 По умолчанию так и есть: восьмой параметр входа — это Δε = eps-1 той среды,
    /// в сечении которой стоит вход (диссертация К. Н. Климова 2007, раздел 7.3,
    /// (7.54)): ядро считает по нему проводимость генератора входа. Вход, стоящий в
    /// диэлектрике с пустым восьмым параметром, согласован с вакуумом, а не со своей
    /// средой, — и об этом никто не скажет. Помнить про это пользователь не обязан:
    /// eps берёт генератор (\ref portEps). Ручное значение остаётся для случаев, где
    /// среду в сечении задаёт не фигура, а модель (эффективная eps микрополоски).
    bool epsAuto = true;
};

/// Восьмой параметр блока INPUT_* — добавка (eps-1). Единица означает «ничего не менять»,
/// и тогда параметр в файл не пишется вовсе: ядро применит своё умолчание.
/// @param[in] p  порт (смотрится ручное значение `Port::eps`)
/// @return true — eps отлична от 1 и восьмой параметр надо писать.
bool portHasEps(const Port &p);

/// Координата плоскости входа с учётом умолчания «на границе области».
/// @param[in] p  порт
/// @param[in] b  счётная область
/// @return Координата плоскости входа, мм: `Port::plane`, если задана, иначе
///         соответствующая граница области (`xMin`, `xMax`, `yMin` или `yMax`).
double portPlane(const Port &p, const Box &b);

/// Проницаемость среды в сечении входа — по фигурам задания (см. \ref Port::epsAuto).
///
/// Берётся диэлектрическая фигура, накрывающая середину апертуры в плоскости входа;
/// из нескольких — нарисованная последней. Ничего не накрывает — вакуум, 1. Плазма и
/// профиль из файла сюда не идут: одного числа у них нет. `variant` — какие фигуры
/// включены на шаге (nullptr — все).
/// @param[in] p        задание (фигуры и область)
/// @param[in] port     порт
/// @param[in] variant  вариант геометрии; nullptr — учитываются все фигуры
/// @return eps среды в середине апертуры (сама eps, не добавка); 1 — вакуум.
/// @see https://www.tamic.ru/docs/theory/ports.html#port-w
double portMediumEps(const struct Project &p, const Port &port,
                     const struct Variant *variant = nullptr);

/// eps, которую эмиттер запишет входу: по среде (\ref Port::epsAuto) или ручная.
/// @param[in] p        задание
/// @param[in] port     порт
/// @param[in] variant  вариант геометрии; nullptr — все фигуры
/// @return eps входа (сама eps); в файл эмиттер пишет добавку eps-1.
double portEps(const struct Project &p, const Port &port, const struct Variant *variant = nullptr);

/// Лежит ли точка в ПЛОЩАДИ фигуры (граница — внутри, с допуском `tol`, мм).
/// У ломаной площади нет: там «в пределах tol от линии».
/// @param[in] s    фигура
/// @param[in] pt   точка в координатах сцены, мм
/// @param[in] tol  допуск, мм (у сектора по дуге — tol/r радиан)
