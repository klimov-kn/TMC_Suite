/// Единица длины, в которой пользователь вводит размеры.
/// В файл всегда пишутся миллиметры (LONG_UNIT mm) — пересчёт делает эмиттер.
enum class LengthUnit { Millimeter, Centimeter, Meter };

/// @brief Переводит длину из единицы ввода в миллиметры.
/// @param[in] value  длина в единицах `from`
/// @param[in] from   единица, в которой задана длина
/// @return Длина, мм.
double toMillimeters(double value, LengthUnit from);
/// @brief Возвращает подпись единицы длины для интерфейса на текущем языке («мм», «см», «м»).
/// @param[in] u  единица длины
/// @return Короткая подпись; пустая строка для неизвестного значения.
QString unitSuffix(LengthUnit u);

/// Счётная область — «коробка», за пределами которой поля не считаются.
struct Box {
    /// Левая граница области по x, мм (координаты сцены).
    double xMin = 0.0;
    /// Правая граница области по x, мм.
    double xMax = 240.0;
    /// Нижняя граница области по y, мм.
    double yMin = 0.0;
    /// Верхняя граница области по y, мм.
    double yMax = 80.0;

    /// @brief Возвращает ширину области по x, мм.
    /// @return `xMax - xMin`, мм.
    double width() const { return xMax - xMin; }
    /// @brief Возвращает высоту области по y, мм.
    /// @return `yMax - yMin`, мм.
    double height() const { return yMax - yMin; }
};

/// Чем заполнена фигура.
///
/// ⚠️ Металл, магнитная стенка и поглотитель рисуются ядром КОНТУРОМ (только периметр),
/// а диэлектрик — ЗАЛИВКОЙ по площади. Редактор обязан показывать это честно, иначе
/// картинка соврёт про то, что посчитает ядро.
enum class Material {
    Metal,      ///< METAL — идеальный проводник
    Magnetic,   ///< MAGNETIC — магнитная стенка
    Absorber,   ///< ABSORBER — поглотитель
    Dielectric  ///< выражение: в файл уходит добавка eps-1
};

/// @brief Сообщает, рисует ли ядро материал контуром (металл, магнитная стенка, поглотитель).
/// @param[in] m  материал фигуры
/// @return true — материал ставится только на периметр; false — диэлектрик (заливка).
bool isContourMaterial(Material m);

/// Плазменные параметры фигуры (только X-мода, ядро tmc_rtx.exe).
///
/// Одна фигура несёт ВСЕ три величины сразу — потому что замагниченная плазма это и
/// есть N вместе с B в одной и той же области. Раньше величина была одна, и задать
/// такую плазму можно было только тремя фигурами друг на друге, помня, что B
/// действует лишь поверх N. Ровно тот случай, который проект обязан закрывать кодом.
///
/// В файл каждая величина уходит ОТДЕЛЬНЫМ блоком с той же геометрией:
/// `RECT_STAT_N` / `_B` / `_Y`. Значение всегда числовое и БЕЗ поправки «минус
/// единица» — эта поправка существует только у eps.
///
/// ⚠️ Как ядро их различает (разобрано по `kernels/PlanarRT_X/TmcRTHRectNode.cpp`,
/// `SetDielInNodeList`, строки 1084-1156; ветки узла — `TmcRTHNodeDiel.cpp:1625`,
/// `prYNode[6*узел + тип]`):
///
///  - **N — это та же добавка eps, только в других единицах.** Ядро переводит её
///    само: `eps_доб -= N*e^2/(m*eps0*(2*pi*f)^2)` (строка 1105) и складывает с
///    добавкой из обычного блока в том же узле. Отсюда два следствия. Первое: N
///    пишется в СИ и один раз — делить её на частоту не нужно, это делает ядро на
///    каждом шаге. Второе: «диэлектрик плюс плазма» в одной области — законная
///    сумма, а не конфликт.
///  - **B — самостоятельная величина**, но входит в расчёт ТОЛЬКО внутри плазменной
///    ветки (`d_WC2 = B^2*(e/m)^2`), а ветка включается при `N != 0` либо при
///    отрицательной добавке eps (условие на строке 1092). Без N подмагничивание
///    молча затирается: в другой ветке `prYNode[ii+4] = -2` (строка 1145).
///  - **Y — тоже самостоятельная**, и это единственная из трёх, которая работает
///    ВЕЗДЕ: она входит в проводимость узла в обеих ветках (строки 1125 и 1147),
///    то есть добавляет потери и там, где никакой плазмы нет.
struct Plasma {
    /// Концентрация N задана (числом, формулой или файлом); false — блок `*_STAT_N` не пишется.
    bool hasN = false;
    double n = 0.0;   ///< концентрация электронов, м^-3 (СИ; N_UNIT ядро не применяет)
    /// Величина из готового файла распределения — блоки `FILE_N`, `FILE_B`, `FILE_Y`.
    ///
    /// Имя без расширения и без точки; пусто — величина задана числом или формулой.
    /// Файл пишет само ядро блоком `RECT_STAT_N [имя]...` (то же для `_B`, `_Y`), и
    /// читается он только прямоугольником: формат хранит регулярную решётку.
    ///
    /// ⚠️ До 26.10.2026 эти блоки не работали ни в одной сборке: разбор сравнивал пять
    /// символов `FILE_` и подменял тег на `FILE `, значения уходили в eps. С 26.10 ядро X
    /// читает их в свои величины, а файл чужой величины отвергает с причиной
    /// (`tpl-guide.md`, раздел 5.7.4). В H-ядре этих блоков нет.
    QString nFile;
    /// Имя файла распределения индукции B (блок `FILE_B`) без расширения; пусто — нет файла.
    QString bFile;
    /// Имя файла распределения параметра Y (блок `FILE_Y`) без расширения; пусто — нет файла.
    QString yFile;
    /// Индукция подмагничивания B задана; false — блок `*_STAT_B` не пишется.
    bool hasB = false;
    double b = 0.0;   ///< индукция подмагничивания, Тесла (B_UNIT ядро не применяет)

    /// Блок B ровно по габариту плазмы, без запаса (см. \ref plasmaBRect).
    ///
    /// По умолчанию блок шире плазмы на два шага (Б-21): на границе блока ядро
    /// ополовинивает значение, и совпадающий блок даёт на краю плазмы N/2 вместе с B/2.
    /// Но краевой слой есть и у широкого блока — там N/2 с полным B, и его
    /// верхнегибридная частота sqrt(fp^2/2 + fce^2) тоже может лечь в полосу: в образце
    /// «Подмагниченная плазма» (fp = 3, fce = 1.5 ГГц) это ровно 2.6 ГГц, и широкий
    /// блок дал там |S11|^2 + |S21|^2 = 1.13, а совпадающий — 1.0006 (прогон ядром X
    /// от 26.10.2026). Автор пакета совпадающие блоки разрешает — с предупреждением.
    /// Чтение ставит флаг, когда блок B в файле совпадает с плазмой: молча расширить
    /// его значило бы посчитать другую задачу.
    bool bExact = false;

    /// Параметр потерь Y задан; false — блок `*_STAT_Y` не пишется.
    bool hasY = false;
    double y = 0.0;   ///< параметр Y (потери в узле), безразмерный — СЕТОЧНАЯ величина

    /// Потери проводимостью σ, См/м — блоки `*_STAT_S` (ядро X с 26.10.2026).
    ///
    /// 🔑 Потери предлагаем задавать именно так, а Y оставляем опытным. Y — сеточная
    /// величина: σ = Y*eps0/(2*dT), а dT зависит от DELTA, поэтому то же Y на вдвое
    /// более мелкой сетке даёт вдвое большее затухание. σ ядро пересчитывает в Y через
    /// шаг само (Y = 2*dT*σ/eps0), и затухание от сетки не зависит (проверено автором
    /// пакета: слой 0.1 См/м на 72 ГГц — |T| 0.347 и 0.349 при DELTA 0.2 и 0.1 мм).
    bool hasS = false;
    /// Удельная проводимость sigma, См/м; действует при `hasS`.
    double s = 0.0;

    /// Профиль вместо числа: выражение от координат.
    ///
    /// Первый параметр блока `*_STAT_N/_B/_Y` ядро считает тем же вычислителем, что и
    /// добавку eps: `CalcEps` подставляет `x`, `y`, `r` и полярный угол `f`
    /// (`kernels/PlanarRT_H/TmcRTHNodeDiel.cpp:1608`). Поэтому
    /// `RECT_STAT_N <выражение от x и y>` — законный блок, и именно так задан
    /// параболический профиль плотности в токамаковых заданиях
    /// (`tmc_full_benchmark_v3_3/tokamak_3horn/PLASMA_PROFILE.H`).
    ///
    /// Пусто — величина задана числом (n/b/y). Непусто — число не используется, а в
    /// файл уходит сама формула. Вычислять её редактор не обязан и не может: у неё
    /// нет одного значения, она разная в каждом узле.
    QString nFormula;
    /// Формула индукции B от x, y, r, f (Тл); пусто — используется число `b`.
    QString bFormula;
    /// Формула параметра Y от x, y, r, f; пусто — используется число `y`.
    QString yFormula;
    /// Формула проводимости sigma от x, y, r, f (См/м); пусто — используется число `s`.
    QString sFormula;

    /// Начало отсчёта x и y в формулах — анкер блока из `#LINK_LIST`.
    ///
    /// Как и у eps, другого способа задать его в языке нет, и в авторских заданиях он
    /// сплошь и рядом стоит не в центре фигуры: у токамака `T 31; 0.0; W_box/2`, то
    /// есть 160 мм по y. Подставить сюда ноль значило бы сдвинуть плазму на полкамеры
    /// при первом же сохранении.
    bool customOrigin = false;
    /// Анкер формул плазмы в координатах сцены, мм; действует при `customOrigin`.
    QPointF origin;

    /// @brief Сообщает, задана ли у фигуры хоть одна плазменная величина (N, B, Y или sigma).
    /// @return true — фигура несёт плазму и рисуется заливкой.
    bool any() const { return hasN || hasB || hasY || hasS; }

    /// Задана ли хоть одна величина формулой, а не числом.
    /// @return true — хотя бы одна из `nFormula`, `bFormula`, `yFormula`, `sFormula` непуста.
    bool hasFormula() const
    {
        return !nFormula.trimmed().isEmpty() || !bFormula.trimmed().isEmpty()
               || !yFormula.trimmed().isEmpty() || !sFormula.trimmed().isEmpty();
    }

    /// Берётся ли хоть одна величина из файла распределения.
    /// @return true — хотя бы одна заданная величина (N, B или Y) берётся из файла.
    bool hasFile() const
    {
        return (hasN && !nFile.trimmed().isEmpty()) || (hasB && !bFile.trimmed().isEmpty())
               || (hasY && !yFile.trimmed().isEmpty());
    }
};

/// Неоднородная среда: eps задана ФОРМУЛОЙ от координат, а не одним числом.
///
/// Ядро умеет это само, и умеет ровно так: если первым параметром блока написать
/// `[имя]выражение`, то при инициализации шага оно посчитает выражение в каждом узле
/// блока и запишет результат в двоичный `<имя>.eps` (`SaveFileRect`, вызывается из
/// `SetRect` — `kernels/PlanarRT_H/TmcRTHNodeDiel.cpp:413`). Обратно этот файл
/// полагается читать блоком `FILE имя;`; в авторских заданиях (`data/CIRCL.H:144-145`)
/// обе строки лежат рядом и переключаются вручную комментарием.
///
/// ⚠️ Читающая половина СЛОМАНА. Блок `FILE` не принимает ни одна из четырёх сборок
/// ядра — шаг останавливается на «Error : Missing separator ;» (проверено прогоном
/// 2026-08-11, подробности в `TMC_Suite/ISSUES.md`). Заметить это по авторским
/// заданиям было нельзя: строка `FILE` там ЗАКОММЕНТИРОВАНА, то есть ядром никогда
/// не читалась. Поэтому эмиттер пишет формулу в каждый шаг, а `[имя]` — только в
/// первый: файл на диске появляется один раз и годится для просмотра, а сам расчёт
/// выражения сэкономить нечем, пока блок `FILE` не починят.
///
/// ⚠️ Только ФАЙЛ ограничен прямоугольником, а не сама формула. `SaveFileRect` зовётся
/// исключительно из `SetRect`; у круга (`SetCirc`) и полигона (`SetPoly`) вызова нет
/// вообще. Причина в формате файла: он хранит `Xmin/Ymin/nX/nY` и ЛИНЕЙНЫЙ индекс узла,
/// из которого координаты восстанавливаются как `j%nX`, `j/nX` (`SetRectFile`, там
/// же:7558). Это регулярная прямоугольная решётка, и поля «узла нет» в ней не
/// предусмотрено — отличить дырку от вакуума нечем.
/// А вот ПОСЧИТАТЬ выражение ядро умеет в любой фигуре: `CIRCLE_STAT <выражение>` —
/// законный блок из авторского задания (`data/cir_quas.h`, блок 20).
///
/// ⚠️ Частоты в выражении НЕТ. `CalcEps` подставляет только `x`, `y`, `r` и `f`, причём
/// `f` — полярный УГОЛ, а не частота (там же:1608). Частотный коэффициент ядро
/// применяет само и на каждом шаге заново (`TmcRTHRectNode.cpp:1052`), поэтому один
/// файл годится на весь свип.
struct EpsProfile {
    /// Профиль включён пользователем; действует, только если `active()` (есть формула или файл).
    bool enabled = false;

    /// Профиль не считается формулой, а ЧИТАЕТСЯ из готового `<file>.eps`.
    ///
    /// В языке это отдельный примитив — `FILE <имя>; x1; x2; y1; y2;`. Файл готовит
    /// не редактор: его пишет либо само ядро (см. \ref file ниже), либо сторонняя
    /// программа, считавшая среду по своей физике — так сделано распределение плазмы
    /// вокруг гиперзвукового аппарата в `samples/error/hyper_sheath_0p4.TPL`.
    ///
    /// ⚠️ До 6 сентября 2026 читающая половина была сломана во ВСЕХ сборках ядра:
    /// диспетчер `#TOPOLOGY` затирал разбираемую строку литералом «FILE » раньше,
    /// чем её читал `ReadFileStat_1`, и шаг останавливался на «Missing separator ;»
    /// (`TMC_Suite/ISSUES.md`, баг #19). Ошибка исправлена в переносе ядра на
    /// macOS/Linux, и блок читается. Редактор обязан такие задания понимать и
    /// возвращать в файл дословно — молча потерять чужой профиль среды нельзя.
    ///
    /// ⚠️ Координаты блока ядро игнорирует: сетка распределения лежит в самом файле
    /// (`#Xmin`/`#Ymin`/`#nX`/`#nY`), а положение на сцене задаёт АНКЕР блока. Мы их
    /// всё равно пишем — по ним фигура видна в редакторе, и так же написаны авторские
    /// задания.
    bool fromFile = false;

    /// Выражение для САМОЙ eps от x, y (мм, от центра фигуры), r и f (угол).
    /// Минус единицу для файла ставит эмиттер — здесь, как и везде, живёт сама eps.
    /// При \ref fromFile не используется: формулы у готового файла нет.
    QString formula;

    /// Имя файла `.eps` без расширения и без точки. Ядро само допишет расширение и
    /// папку задания (`AddFileEpsExtention`).
    ///
    /// При \ref fromFile — ОТКУДА читать, и тогда имя обязательно. Иначе — КУДА
    /// записать посчитанное; пусто означает, что файл не пишется вовсе, а формула
    /// просто считается в узлах.
    QString file;

    /// Начало отсчёта x и y в формуле, если оно НЕ в центре фигуры.
    ///
    /// В языке это анкер блока (строка `#LINK_LIST`), и другого способа задать его нет.
    /// Обычно удобнее всего центр — формула тогда не зависит от того, где фигура лежит
    /// на сцене, — но авторские задания этим пользуются иначе: в `data/cir_quas.h`
    /// прямоугольник 28 лежит по x от 140 до 412, а координаты формулы отсчитаны от
    /// 550, то есть от центра сосуда снаружи фигуры. Жёстко ставить центр значило бы
    /// молча сдвинуть среду на 274 мм при первом же сохранении.
    bool customOrigin = false;
    /// Анкер формулы в координатах сцены, мм; действует при `customOrigin`.
    QPointF origin;

    /// @brief Сообщает, действует ли профиль: включён и задан формулой либо именем файла.
    /// @return true — фигура пишется с профилем eps вместо числа `Shape::eps`.
    bool active() const
    {
        if (!enabled)
            return false;
        return fromFile ? !file.trimmed().isEmpty() : !formula.trimmed().isEmpty();
    }

    /// Просили ли записать посчитанное в файл. Это отдельное желание пользователя:
    /// формула работает и без файла, а файл нужен, только чтобы профиль посмотреть.
    /// У профиля ИЗ файла записи нет: там файл — источник, а не результат.
    /// @return true — профиль считается формулой и результат надо сохранить в `<file>.eps`.
    bool savesFile() const { return active() && !fromFile && !file.trimmed().isEmpty(); }

    /// Профиль берётся из готового файла — блок уйдёт в задание как `FILE <имя>;`.
    /// @return true — профиль читается из готового файла `<file>.eps`.
    bool readsFile() const { return active() && fromFile; }
};

