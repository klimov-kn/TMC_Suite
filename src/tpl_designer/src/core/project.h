bool shapeCovers(const struct Shape &s, const QPointF &pt, double tol = 0.0);

/// Направление, которое ВЫВЕДЕТ ядро для входа, стоящего в этой плоскости.
/// Считает ровно так же, как `TmcRTH_IndanTopology.cpp`: по половине коробки.
