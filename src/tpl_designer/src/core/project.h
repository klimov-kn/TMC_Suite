/// Верхняя граница прямоугольника, мм.
/// @var Shape::vy
/// Скорость движения блока по y (блоки `*_MOVE`).

/// Знаковая площадь ломаной. > 0 — обход против часовой стрелки (ось Y вверх).
/// Нужна эмиттеру: заливному полигону ядро требует обход ПО часовой.
