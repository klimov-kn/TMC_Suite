#pragma once

// Размещение фигур относительно друг друга и сетки: где ядро молча посчитает не то,
// что нарисовано. Проверки по ответам К. Н. Климова 26.10.2026
// (`docs/requirements-2026-10-26.md`, `docs/plasma-placement-rules.md`).

/// @file placement.h
/// @brief Проверки размещения фигур относительно сетки и друг друга, блок B шире плазмы,
///        оценка времени установления и безопасный конец окна ДН.
///
/// Часть ядра TPL Designer. Вызывается из `validate` (emitter.h) и эмиттером
/// (`plasmaBRect`, `patternWindowSafeEnd`); замечания — только о том, что ядро отвергнет
/// или молча посчитает не так, как нарисовано.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#placement

#include "emitter.h"

namespace tpl {

/// Прямоугольник, мм, в координатах сцены.
/// @brief Прямоугольник по осям в координатах сцены, мм.
struct RectMm {
    /// @name Границы прямоугольника
    ///@{
    /// Границы прямоугольника: xLo...xHi по X, yLo...yHi по Y, мм.
    double xLo = 0.0, xHi = 0.0, yLo = 0.0, yHi = 0.0;
    ///@}
};

/// На сколько шагов сетки блок B выходит за плазму с каждой стороны.
inline constexpr int kBMarginCells = 2;

/// Где эмиттер запишет блок подмагничивания `RECT_STAT_B` фигуры (координаты сцены).
///
/// 🔑 Шире плазмы на \ref kBMarginCells шага с каждой стороны, обрезано по области.
/// На границе блока ядро ополовинивает значение, в углу делит на четыре — для всех
/// величин (Б-21). Если блок B совпадает с плазмой, на её краю оказываются N/2 и B/2
/// со своей верхнегибридной частотой, и тонкий слой становится ложным резонансом
/// (B = 5 Тл: |R| = 0.40 вместо 0.002). Вне N поле B ни на что не влияет, так что
/// шире — безопасно.
///
/// Сторона НЕ расширяется, если тогда блок задел бы ЧУЖУЮ плазму, которой он раньше
/// не касался, или формула B за пределами фигуры перестала бы давать число.
/// `widened` — получилось ли расширить хоть одну сторону.
/// @param[in]  p        проект (шаг `delta`, область `box`, остальные фигуры).
/// @param[in]  s        фигура с плазмой и полем B.
/// @param[out] widened  если не `nullptr` — true, если расширена хоть одна сторона.
/// @return Прямоугольник блока B, мм; совпадает с габаритом фигуры при `bExact` или `delta <= 0`.
/// @see https://www.tamic.ru/docs/theory/plasma.html#model
RectMm plasmaBRect(const Project &p, const Shape &s, bool *widened = nullptr);

/// Через сколько наносекунд после включения поле в области успевает установиться —
/// грубая оценка снизу: волна проходит диагональ области в самой «медленной» среде.
/// 0 — у задания нет непрерывного возбуждения (импульс), установившегося режима нет.
/// @brief Оценивает момент установления поля: start + diag * sqrt(eps_max) / c.
/// @param[in] p  проект (активные порты, фигуры-диэлектрики, область).
/// @return Время, нс, от нуля счёта; 0, если нет активного порта с непрерывной формулой.
double steadyStateTime(const Project &p);

/// Отступ контура ДН от края области, мм: ядро ставит его ровно в 10 шагах сетки
/// (`FieldIntegrated.cpp`, `SetDirectionalPatternParamDefault`).
/// @param[in] p  проект (шаг `delta`).
/// @return Отступ 10 * DELTA, мм.
/// @see https://www.tamic.ru/docs/theory/radiation.html#contour
double patternContourMargin(const Project &p);

/// Конец окна ДН не позже `want`, при котором окно закроется на любой частоте задания.
///
/// Ядро дотягивает окно ДН до целого числа периодов, `(int)((Tmax-Tmin)*f + 0.9999)`
/// (Б-13), и окно, кончающееся не раньше TIME, не закрывает вовсе: файлов ДН нет.
/// Поэтому «до конца счёта» — это не TIME, а TIME минус период самой низкой частоты.
/// @param[in] p     проект (частоты `freqs`, время счёта `timeMax`).
/// @param[in] tMin  начало окна ДН, нс.
/// @param[in] want  желаемый конец окна, нс.
/// @return `want`, если окно закрывается; иначе наибольший конец <= TIME - 1/f_min,
///         округлённый вниз до 0.01 нс и уменьшаемый по 0.01 нс, пока окно не закроется.
double patternWindowSafeEnd(const Project &p, double tMin, double want);

/// Закроет ли ядро окно ДН `tMin...tMax` на всех частотах задания.
/// @brief Проверяет, что окно ДН, дотянутое ядром до целого числа периодов, кончается раньше TIME.
/// @param[in] p     проект (частоты, время счёта).
/// @param[in] tMin  начало окна, нс.
/// @param[in] tMax  конец окна, нс.
/// @return true — на каждой частоте tMin + ceil((tMax-tMin)*f)/f < TIME.
/// @see https://www.tamic.ru/docs/theory/radiation.html#pattern
bool patternWindowCloses(const Project &p, double tMin, double tMax);

/// Предупреждения и ошибки размещения — дописываются в `d`.
/// @brief Проверяет размещение и дописывает замечания.
///
/// Проверяет: фигуру, частично выходящую за область дальше полушага (ядро отбросит
/// часть); магнитную стенку или поглотитель (круг, полигон) меньше ячейки 2*DELTA;
/// в ядре X — границу блока B, режущую плазму, краевой резонанс плазмы в полосе,
/// плазму и eps > 1 в одних узлах, B в диэлектрике без N, подмагниченную плазму у
/// магнитной стенки, плазму на поглотителе, добавку eps около 4; окно S-матрицы и ДН
/// до установления; окно ДН, которое ядро не закроет (ошибка); поглотитель, плазму и
/// вход относительно контура ДН (10 шагов от края).
/// @param[in]     p  проект.
/// @param[in,out] d  замечания: ошибки в `errors`, предупреждения в `warnings`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#placement
void checkPlacement(const Project &p, Diagnostics *d);

} // namespace tpl
