// Язык текстов TPL Designer: русский (по умолчанию) или английский.
//
// Действует на всё, что генератор пишет и показывает: надписи окон, замечания проверки,
// комментарии и имена в файле задания .tpl, тексты библиотеки образцов. Русский текст —
// исходный и остаётся прежним байт в байт; английский — второй аргумент tr().
//
// Выбор языка — общий для пакета (Настройки → Language / Язык); окно передаёт его сюда
// через setEnglish(). Ядро генератора (tpl_core) при этом зависит только от Qt6::Core.
//
// ⚠️ Переведённый текст нельзя запоминать в static: он вычислится один раз на том языке,
// который действовал при первом обращении. Таблицы текстов — функциями, а не константами.

/// @file lang.h
/// @brief Язык текстов редактора заданий: русский или английский (`tpl::tr`).
///
/// Часть ядра TPL Designer (`tpl_core`). Флаг языка — один на процесс; его выставляет
/// интерфейс при запуске и при смене языка в меню. Все строки для человека, в том числе
/// комментарии и имена, уходящие в `.tpl`, берутся через `tr(ru, en)`.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#translation
#pragma once

#include <QString>

namespace tpl {

/// Включить английский (true) или русский (false). По умолчанию — русский.
/// @brief Переключает язык текстов генератора.
/// @param[in] on  true — английский, false — русский.
/// @note Потоки: флаг не защищён; менять только из потока интерфейса, пока не идёт генерация.
void setEnglish(bool on);

/// Действующий язык — английский?
/// @brief Сообщает, выбран ли английский язык.
/// @return true — английский, false — русский (по умолчанию).
bool english();

/// Строка на действующем языке. Оба аргумента — UTF-8.
/// @brief Возвращает русский или английский вариант текста по действующему языку.
/// @param[in] ru  русский текст, UTF-8 (исходный; при русском языке уходит в файлы байт в байт).
/// @param[in] en  английский текст, UTF-8; в строках, уходящих в `.tpl`, — только ASCII.
/// @return Выбранная строка; вычисляется при каждом вызове (не кэшировать в `static`).
inline QString tr(const char *ru, const char *en)
{
    return QString::fromUtf8(english() ? en : ru);
}

} // namespace tpl
