/// @file sigfile.h
/// @brief Файл падающей волны `.sig`: формы сигнала, значения a(t), план записи, шапка и разбор.
///
/// Часть ядра TPL Designer. Используется эмиттером (имя файла в `[...]` на месте `Amp`),
/// проверкой (окна, полоса, тоны), записью задания (`signalCompanions`) и галереей форм.
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#sig-file
#pragma once

#include "project.h"

#include <QByteArray>
#include <QMap>
#include <QString>
#include <QVector>

/// Файл падающей волны `.sig`: формы сигнала, которые ядру не выразить формулой.
///
/// Ядро умеет ровно одно произведение: `a = Amp(t,f)*sin(2*pi*FREQ*t + Faza)`.
/// Гребёнка тонов, ЛЧМ, пила, видеоимпульс без несущей и «любая форма, какую
/// вздумается» в него не укладываются. Поэтому в ядра пакета добавлен второй путь
/// (правка 2026-09-30): на месте `Amp` стоит имя файла в квадратных скобках, и файл
/// задаёт ВСЮ `a(t)` — `INPUT_X ; ylo; yhi; Tmin; Tmax; [wg_multi]; 0;`.
///
/// Здесь — всё про этот файл: какие бывают формы, как считается значение, каким
/// шагом писать и что положить в шапку. Ни одного виджета: картинку в галерее
/// рисует GUI по тем же самым числам, что уйдут в файл, — иначе картинка соврёт.
namespace tpl {

/// Скомпилированная формула (expr.h).
class ExprProgram;

/// Шаг по времени самого ядра, нс: `DELTA/(c*sqrt(2))`. При DELTA = 1 мм — 0.00236 нс.
/// @brief Вычисляет шаг ядра по времени dt = DELTA / (c * sqrt(2)).
/// @param[in] deltaMm  шаг сетки DELTA, мм.
/// @return Шаг, нс; 0 при `deltaMm <= 0`.
/// @see https://www.tamic.ru/docs/theory/method.html#time-step
double kernelTimeStep(double deltaMm);

/// Полоса, которую занимает сигнал.
/// @brief Полоса частот сигнала, ГГц.
struct Band {
    double lo = 0.0; ///< ГГц
    double hi = 0.0; ///< ГГц
    bool known = false; ///< у произвольной формулы и таблицы полосы мы не знаем

    /// @return Середина полосы (lo + hi) / 2, ГГц.
    double center() const { return (lo + hi) / 2.0; }
    /// @return Ширина полосы hi - lo, ГГц.
    double width() const { return hi - lo; }
};

/// Какие поля формы имеют смысл. По нему диалог показывает ровно нужные строки,
/// а не двенадцать полей сразу.
/// @brief Набор параметров, которые имеют смысл для формы сигнала (что показывать в диалоге).
struct WaveFields {
    bool band = false;       ///< f1 и f2 — границы полосы
    bool tones = false;      ///< число тонов гребёнки
    bool carrier = false;    ///< f1 — несущая
    bool rate = false;       ///< f1 — частота повторения
    bool periods = false;    ///< периодов в посылке
    bool duration = false;   ///< длительность посылки
    bool width = false;      ///< tau гауссовой шапки
    bool edges = false;      ///< фронт и спад
    bool expression = false; ///< формула a(t)
    bool table = false;      ///< таблица точек
};

/// @brief Сообщает, какие параметры использует форма сигнала.
/// @param[in] k  форма сигнала.
/// @return Флаги нужных полей.
WaveFields waveFields(Waveform k);

/// Название формы для галереи.
/// @brief Возвращает название формы на действующем языке.
/// @param[in] k  форма сигнала.
/// @return Название, например «Гребёнка тонов».
QString waveformName(Waveform k);
/// Одна строка: чем форма хороша и для чего её берут.
/// @brief Возвращает однострочную подсказку о назначении формы.
/// @param[in] k  форма сигнала.
/// @return Текст подсказки на действующем языке.
QString waveformHint(Waveform k);
/// Что получится при этих параметрах: «10 тонов 3...4.8 ГГц, посылка 40 нс».
/// @brief Составляет краткое описание сигнала с его параметрами.
/// @param[in] w  параметры сигнала.
/// @return Строка для подписи в диалоге и в шапке `.sig`.
QString waveshapeSummary(const Waveshape &w);

/// Опора сигнала, нс: вне неё в файле точек нет, и ядро вернёт ноль.
/// @brief Вычисляет интервал, на котором сигнал отличен от нуля.
///
/// Гребёнка, ЛЧМ, периодические формы и формула — [start; start + duration];
/// посылка синуса — N периодов несущей; гауссовы формы — 6 tau; трапеция —
/// фронт + полка + спад; таблица — от первой до последней точки.
/// @param[in] w  параметры сигнала.
/// @return Окно [tMin; tMax], нс.
TimeWindow waveSupport(const Waveshape &w);

/// Полоса сигнала. Для формулы и таблицы — `known == false`.
/// @brief Оценивает полосу сигнала.
///
/// Гребёнка и ЛЧМ — [f1; f2]; посылка синуса — f1 -+ f1/N; радиоимпульс — f1 -+ 1.52/(pi*tau)
/// (уровень -20 дБ); видеоимпульс и моноцикл — [0; 1.52/(pi*tau)]; трапеция —
/// [0; 1/(pi*фронт)]; пила, треугольник, меандр — [f1; 10*f1]; таблица — по тонам `#FREQ`.
/// @param[in] w  параметры сигнала.
/// @return Полоса, ГГц; `known == false` для формулы и таблицы без тонов.
Band waveBand(const Waveshape &w);

/// Частота СОГЛАСОВАНИЯ порта, которую стоит поставить в `FREQ`, ГГц.
///
/// 🔑 Это не то же самое, что центр полосы. У гребёнки и ЛЧМ — да, центр. А у пилы
/// и меандра спектр тянется до десятой гармоники, и центр такого «диапазона» (21 ГГц
/// при повторении 3.9) к согласованию порта отношения не имеет: вся энергия сидит на
/// основной частоте, по ней и согласуют. У радиоимпульса и посылки согласуют по
/// несущей, у видеоимпульса — по середине его полосы от нуля.
///
/// Возвращает 0, если подсказать нечего (своя формула, своя таблица).
/// @param[in] w  параметры сигнала.
/// @return Рекомендуемая `FREQ`, ГГц; 0 — подсказать нечего.
/// @see https://www.tamic.ru/docs/theory/ports.html#incident-file
double suggestedFreq(const Waveshape &w);

/// Число с правильным словом: «10 тонов», «1 тон», «2 тона».
/// @brief Согласует число со словом (по-русски — три формы, по-английски — две).
/// @param[in] n     число.
/// @param[in] one   форма для 1 (21, 31 ...).
/// @param[in] few   форма для 2-4 (22-24 ...); по-английски не используется.
/// @param[in] many  форма для 5-20 и прочих.
/// @return Строка «n слово».
QString plural(int n, const QString &one, const QString &few, const QString &many);

/// Тоны для строки `#FREQ`. Пусто — строку не пишем.
///
/// 🔑 Строка нужна ТОЛЬКО многотону. Автоматически искать тоны по спектру нельзя:
/// соседние линии смещают пики друг друга, и на проверенном сигнале максимум
/// приходился на 2.9973 вместо 3.000 ГГц — постобработка расходилась на 0.7 дБ
/// вместо 0.002. У импульса спектр гладкий, частоты берутся любые, и `#FREQ` ему
/// только помешал бы.
/// @param[in] w  параметры сигнала.
/// @return Тоны гребёнки (max(2, tones) равноотстоящих от f1 до f2) или `tableTones` таблицы, ГГц;
///         для остальных форм — пусто. Список не обрезается до `kMaxFreqs`.
QVector<double> waveTones(const Waveshape &w);

/// Готовая к счёту формула произвольной формы. Разбирается ОДИН раз: точек в файле
/// десятки тысяч, и разбор строки на каждую был бы виден глазом.
/// Для остальных форм возвращает невалидную программу — она и не нужна.
/// @param[in] w  параметры сигнала.
/// @return Программа формулы a(t) (углы в радианах) или пустая программа для других форм.
ExprProgram waveProgram(const Waveshape &w);

/// Значение `a(t)`, t в нс. Ровно то, что уйдёт в файл и что рисует галерея.
/// \p prog — разобранная формула для Waveform::Expression; без неё такая форма даёт 0.
/// @brief Вычисляет значение падающей волны в момент времени.
///
/// Гребёнка — A * sum(sin(2*pi*f_i*u)) с плавным включением на первых 5 % посылки
/// (каждый тон с полной амплитудой A); ЛЧМ — фаза 2*pi*(f1*u + (f2-f1)*u^2/(2*T));
/// гауссовы формы центрированы в start + 3*tau; таблица — линейная интерполяция, вне неё 0.
/// @param[in] w     параметры сигнала (амплитуда безразмерная).
/// @param[in] tNs   время, нс.
/// @param[in] prog  разобранная формула для `Waveform::Expression` (иначе не используется); `nullptr` -> 0.
/// @return Значение a(t), безразмерное; вне `waveSupport` — 0.
double waveValue(const Waveshape &w, double tNs, const ExprProgram *prog = nullptr);

/// Наибольшее по модулю значение сигнала — для подписи «пик».
/// У гребёнки тонов пик доходит до N*амплитуд, и умалчивать об этом нельзя.
/// @param[in] w  параметры сигнала.
/// @return Пиковое |a|: у гребёнки и формулы — максимум по 40001 выборке посылки,
///         у таблицы — максимум точек, у остальных — |A|.
double wavePeak(const Waveshape &w);

/// Как будет записан файл: шаг, число точек, границы.
/// @brief План записи файла `.sig`: шаг, интервал и число точек (время — нс).
struct SigPlan {
    double kernelDt = 0.0; ///< шаг ядра, нс
    double dt = 0.0;       ///< шаг записи, нс — вдвое мельче шага ядра
    double from = 0.0;     ///< первая точка, нс
    double to = 0.0;       ///< последняя точка, нс
    /// Число точек в файле (не больше 400 000).
    int points = 0;
    bool coarsened = false; ///< шаг укрупнён, чтобы файл не распух
    bool cutByTime = false; ///< хвост сигнала за концом счёта TIME
};

/// Сколько точек и каким шагом писать.
///
/// Шаг берём ВДВОЕ МЕЛЬЧЕ шага ядра: проверено прогоном — вдвое крупнее ядерного
/// даёт ошибку 7e-3, вдвое мельче 6e-5. Ядро между точками интерполирует линейно.
/// @param[in] p     проект (шаг `delta`, время счёта `timeMax`).
/// @param[in] port  порт с сигналом из файла.
/// @return План: dt = шаг ядра / 2; интервал — опора сигнала, обрезанная по [0; TIME];
///         при превышении 400 000 точек шаг укрупняется (`coarsened`).
/// @see https://www.tamic.ru/docs/theory/ports.html#incident-file
SigPlan sigPlan(const Project &p, const Port &port);

/// Имя файла сигнала без расширения — то, что встанет в квадратные скобки.
/// @param[in] p     проект (имя задания).
/// @param[in] port  порт.
/// @return Имя, заданное в порту, или `<имя задания>_in<порядковый номер порта>` (`task_in1` без имени).
QString signalFileName(const Project &p, const Port &port);

/// Служебная строка в шапке `.sig`, по которой чтение узнаёт форму обратно.
/// @brief Метка служебной строки `.sig` с параметрами формы (`kind=...; amp=...; ...`).
inline constexpr const char *kSigMarker = "@TPLD-SIG";

/// Текст файла `.sig` целиком: шапка с пояснениями, `@TPLD-SIG`, при многотоне
/// `#FREQ`, дальше две колонки «время в нс, значение».
/// @param[in] p     проект.
/// @param[in] port  порт с сигналом из файла.
/// @return Текст с переводами строк LF (CRLF и CP1251 — при записи); числа «%16.9f  %18.9e».
/// @note В `#FREQ` пишется не больше `kMaxFreqs` тонов; о срезе говорит комментарий в файле.
QString sigFileText(const Project &p, const Port &port);

/// Разобрать служебную строку обратно в форму. false — строки нет или она чужая.
/// @param[in]  line  строка шапки `.sig`.
/// @param[out] out   форма, восстановленная из строки (заполняется только при успехе).
/// @return true — строка содержит `@TPLD-SIG` с допустимым `kind`.
bool parseSigMarker(const QString &line, Waveshape *out);

/// Точки из текста файла `.sig`: две колонки, `!` и `#` — комментарии.
/// Читается ровно как читает ядро (`ReadSignalFile`), включая `#FREQ`.
/// @param[in] text  текст файла `.sig`.
/// @return Точки (x — время в `TIME_UNIT` файла, y — значение); строки короче двух чисел пропускаются.
QVector<QPointF> parseSigPoints(const QString &text);

/// Тоны из строки `#FREQ` файла `.sig` — ВСЕ, сколько их там есть, без обрезки.
/// Пусто — строки нет (у импульса её и не бывает). Обрезка до \ref kMaxFreqs — дело
/// записи; здесь нужен полный список, чтобы честно сказать, сколько отброшено.
/// @param[in] text  текст файла `.sig`.
/// @return Тоны последней строки `#FREQ` (как у ядра — строка без отступа, чтение до первого нечисла).
QVector<double> parseSigTones(const QString &text);

/// Что сказать человеку, принёсшему файл с тонами больше \ref kMaxFreqs : сколько их,
/// до какой частоты возьмётся и сколько отброшено. Пусто — обрезать нечего.
/// @param[in] tones  полный список тонов.
/// @return Текст предупреждения на действующем языке или пустая строка, если тонов не больше 99.
QString toneCutNotice(const QVector<double> &tones);

/// Все файлы сигналов задания: имя С расширением -> байты в CP1251.
/// \p lossy — что-то не легло в CP1251 (тогда писать файл нельзя).
/// @param[in]     p      проект.
/// @param[in,out] lossy  если не `nullptr` — к нему добавляется (через ИЛИ) признак потери символов.
/// @return Имя файла `.sig` -> содержимое в CP1251 с CRLF, для каждого излучающего порта с сигналом из файла.
QMap<QString, QByteArray> signalCompanions(const Project &p, bool *lossy = nullptr);

/// Пойдёт ли файл сигнала этого порта В ДЕЛО.
///
/// Порт может быть помечен активным вручную либо стоять в очереди возбуждений — и то и
/// другое означает, что он излучает. У пассивного порта эмиттер пишет на месте `Amp`
/// ноль, а не имя файла, поэтому файл для него был бы лишним: он лёг бы рядом с
/// заданием, на него никто бы не ссылался, и человек гадал бы, зачем он там.
/// @param[in] p     проект (очередь возбуждений `exciters`).
/// @param[in] port  порт.
/// @return true — сигнал порта из файла и порт активен или стоит в очереди возбуждений.
bool portUsesSignalFile(const Project &p, const Port &port);

/// Есть ли активный порт с сигналом из файла. Такое задание широкополосное:
/// `FREQ` в нём — частота СОГЛАСОВАНИЯ порта, и её ставят в центр полосы.
/// @param[in] p  проект.
/// @return true — хотя бы один порт излучает сигнал из файла.
bool hasFileSignal(const Project &p);

/// Полоса всех широкополосных портов задания вместе.
/// @param[in] p  проект.
/// @return Объединение известных полос всех излучающих портов с сигналом из файла;
///         `known == false`, если таких полос нет.
Band projectBand(const Project &p);

} // namespace tpl
