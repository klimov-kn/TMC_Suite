#pragma once

// Треугольная сетка 3D-модели — то, во что превращается любой принесённый файл
// (STL, OBJ, STEP), прежде чем его разрежут плоскостью.
//
// Только Qt::Core: модель читается и режется без окон, и это проверяют тесты.

/// @file mesh3d.h
/// @brief Треугольная сетка 3D-модели: вершины, треугольники, тела; склейка вершин и масштаб.
///
/// Часть импорта 3D в ядре TPL Designer: общий формат для STL, OBJ и STEP перед срезом
/// плоскостью (`sliceMesh`).
/// @see https://www.tamic.ru/docs/code/tpl-designer.html#mesh-import

#include <QString>
#include <QVector>

#include <array>
#include <cstdint>

namespace tpl {

/// @brief Точка или вектор в пространстве (единицы — как у сетки: после `scale` мм).
struct Vec3 {
    /// @name Координаты
    ///@{
    /// Координаты x, y, z.
    double x = 0.0, y = 0.0, z = 0.0;
    ///@}
};

/// Габарит модели.
/// @brief Габаритный параллелепипед: углы `lo`, `hi`; `valid == false` у пустой сетки.
struct Bounds3 {
    /// @name Углы габарита
    ///@{
    /// Нижний (`lo`) и верхний (`hi`) углы габарита.
    Vec3 lo, hi;
    ///@}
    /// true — габарит посчитан хотя бы по одной вершине.
    bool valid = false;
    /// @return Центр габарита.
    Vec3 center() const { return {(lo.x + hi.x) / 2, (lo.y + hi.y) / 2, (lo.z + hi.z) / 2}; }
    /// @brief Возвращает длину диагонали габарита.
    /// @return Диагональ; 0 у невалидного габарита.
    double size() const; ///< диагональ
};

/// Тело модели: кусок сетки с одним именем и одним материалом.
///
/// Из STL это `solid <имя>` или сам файл, из OBJ — объект/группа с `usemtl`, из STEP —
/// тело сборки. Срез режет тела ПОРОЗНЬ: у каждого свой материал, и сливать их контуры
/// нельзя — граница меди и тефлона есть граница двух фигур.
struct MeshBody {
    QString name;     ///< имя тела, как в файле
    QString material; ///< имя материала, как в файле (пусто — не задан)
    /// true — в файле задан цвет тела (`rgb`).
    bool hasColor = false;
    std::uint32_t rgb = 0xA0A8B8; ///< цвет из файла — только для показа
    /// Номер первого треугольника тела в `Mesh::tris`.
    int firstTri = 0;
    /// Число треугольников тела.
    int triCount = 0;
};

/// Сетка: общие вершины, треугольники по три номера, тела — непрерывные куски треугольников.
/// @brief Треугольная сетка модели; создаётся читателями (`readMeshFile`, `readStepFile`).
struct Mesh {
    /// Вершины (после `weld` — без повторов).
    QVector<Vec3> vertices;
    /// Треугольники: три номера вершин.
    QVector<std::array<int, 3>> tris;
    /// Тела — непрерывные отрезки `tris`.
    QVector<MeshBody> bodies;

    /// @return true — нет ни одного треугольника.
    bool isEmpty() const { return tris.isEmpty(); }
    /// @brief Вычисляет габарит по всем вершинам.
    /// @return Габарит; `valid == false` у сетки без вершин.
    Bounds3 bounds() const;

    /// Склеить совпадающие вершины.
    ///
    /// 🔑 Без этого срез не собирается в контуры. STL хранит каждый треугольник со
    /// СВОИМИ тремя вершинами, и у соседних треугольников общая вершина записана
    /// дважды. Склеенная сетка даёт рёбрам общие номера, а по номеру ребра отрезки
    /// среза сшиваются ТОЧНО, без допусков по расстоянию.
    /// \p tol — расстояние, ближе которого вершины считаются одной; 0 — доля габарита.
    /// @brief Склеивает вершины ближе `tol` (поиск по решётке с шагом `tol`, 27 соседних ячеек)
    ///        и выбрасывает выродившиеся треугольники.
    /// @param[in] tol  расстояние склейки в единицах сетки; <= 0 — 1e-7 диагонали габарита (не меньше 1e-12).
    void weld(double tol = 0.0);

    /// Масштаб: единицы файла -> мм.
    /// @brief Умножает все координаты на коэффициент.
    /// @param[in] k  множитель перевода единиц файла в мм (например 25.4 для дюймов).
    void scale(double k);

};

} // namespace tpl
