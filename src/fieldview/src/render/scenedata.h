// Что рисует сцена FieldView: всё уже пересчитано в координаты сцены (как
// XtoGLWinCoord / YtoGLWinCoord / ZtoGLWinCoord Windows-версии), рендерер только
// раскладывает это по буферам видеокарты.
//
// Слой сетки (поле или ε): координаты узлов (u, v) лежат в видеопамяти один раз на
// размер сетки, значения такта — буфер, обновляемый при смене кадра; высота и цвет
// считаются в шейдере: h = v·k + off (ZtoGLWinCoord), цвет — (h+1)/2 или |h| (SetColor).
/// @file scenedata.h
/// @brief Описание сцены FieldView для вывода: слои сетки (поле, eps), цветная геометрия, надписи, картинки.
///
/// Часть модуля FieldView (слой `render`). Структуры заполняет `FieldPane`, читает
/// `FieldRhiView`. Поля `*Version` — счётчики изменений: вид перезаливает буфер
/// видеокарты, только когда номер изменился.
/// @see https://www.tamic.ru/docs/code/fieldview.html#scene
#pragma once

#include <QColor>
#include <QFont>
#include <QImage>
#include <QRectF>
#include <QString>
#include <QVector3D>

#include <memory>
#include <vector>

namespace fieldview {

/// @brief Наибольшее число узлов сетки сцены по стороне (узлов).
///
/// Наибольшее число узлов сетки сцены по стороне (С-62). Буферы видеокарты адресуются
/// 32-битными размерами и индексами: сетка 16384×16384 (индексы треугольников — 24 байта на
/// ячейку) их переполняла. Окно данных больше этого показывается каждым k-м узлом
/// (FieldPane::updateWindow); значения узлов не меняются.
constexpr int kMaxSceneSide = 4096;

/// @brief Слой сетки (поле или eps): значения узлов и правила высоты и цвета.
///
/// Высота точки в сцене `h = v * k + off` (нормирована к [-1, 1] по пределам Z), цвет —
/// по шкале в точке `t = (h + 1) / 2` или `t = |h|`. Вычисляется в шейдере `grid.vert`.
/// @see https://www.tamic.ru/docs/code/fieldview.html#shaders
struct GridLayer
{
    /// Слой рисуется.
    bool visible = false;
    /// Рисовать заливку (треугольники ячеек).
    bool surface = false;
    /// Рисовать каркас (линии сетки).
    bool line = false;
    /// Рельеф (3D): высота по значению; `false` — плоская карта.
    bool dim3d = false;
    /// Непрозрачность слоя, 0 … 1.
    float alpha = 1.0f;          // nBlend / 100
    /// Значения узлов окна данных, `nX * nY`, строка за строкой (общая память с кадром или копия).
    std::shared_ptr<const std::vector<float>> values;   // nX·nY значений слоя
    /// Номер изменения значений.
    quint64 valuesVersion = 0;
    /// @name Перевод значения в нормированную высоту h = v * k + off
    ///@{
    /// Множитель и сдвиг: `k = 2 / (zMax - zMin)`, `off = -2 * zMin / (zMax - zMin) - 1`.
    float k = 1.0f, off = 0.0f;  // h = v·k + off
    ///@}
    /// Правило цвета: 0 — t = (h + 1) / 2; 1 — t = |h| (режим «Модуль»).
    int colorMode = 0;           // 0 — (h+1)/2, 1 — |h| (режим «Модуль»)
    /// Число ступеней цвета: 0 — плавно; 20 — 20 уровней.
    int levels = 0;              // 0 — плавно, 20 — 20 уровней цвета
    /// Множитель высоты рельефа (в 2D не действует).
    float heightScale = 1.0f;    // множитель высоты рельефа (в 2D не действует)
    /// Шкала цвета: картинка 256 x 1, RGBA8.
    QImage palette;              // 256×1 RGBA8
    /// Номер изменения шкалы.
    quint64 paletteVersion = 0;
    /// Цвет каркаса поверх заливки (без заливки каркас окрашивается по шкале).
    QColor wireColor;            // цвет каркаса поверх заливки
    /// Высота плоского слоя над плоскостью z = 0 в единицах сцены (в 2D).
    float zLift2D = 0.0f;        // высота плоского слоя (2D)
};

/// @brief Надпись в точке сцены (рисуется поверх кадра в пикселях окна).
///
/// Надпись, привязанная к точке сцены.
struct SceneLabel
{
    /// Точка привязки в координатах сцены.
    QVector3D pos;
    /// Текст надписи.
    QString text;
    /// Цвет текста.
    QColor color;
    /// Выравнивание: 0 — справа от точки, 1 — по центру, 2 — слева.
    int align = 0;               // 0 — справа от точки, 1 — по центру, 2 — слева
};

/// @brief Картинка поверх сцены в пикселях окна.
///
/// Картинка поверх сцены в пикселях окна (надписи, шкала, сведения о такте).
struct Sprite
{
    /// Картинка RGBA8888 с предумноженной альфой; учитывает плотность точек экрана.
    QImage image;                // RGBA8888_Premultiplied, с devicePixelRatio
    /// Место на окне, логические пиксели (ось Y вниз).
    QRectF rect;                 // логические пиксели окна
    /// Номер изменения картинки.
    quint64 version = 0;
    /// Картинка рисуется.
    bool visible = true;
};

/// @brief Всё, что рисует вид за кадр: два слоя сетки, цветная геометрия, надписи, габариты.
///
/// Координаты сцены: сетка занимает прямоугольник 2,5 * kx на 2,5 * ky с центром в нуле
/// (kx, ky — пропорции окна данных), ось Z — нормированная высота. Владелец — `FieldPane`;
/// вид хранит указатель и читает данные в своём `render()` (тот же поток интерфейса).
/// @see https://www.tamic.ru/docs/code/fieldview.html#scene
struct SceneData
{
    /// @name Размер сетки сцены, узлов
    ///@{
    /// Узлы окна данных после прореживания; 0 — сетки нет.
    int nX = 0, nY = 0;          // сетка показываемого окна данных
    ///@}
    /// @name Размещение сетки в сцене
    ///@{
    /// Узел (j, i) лежит в точке (x0 + sx * j / (nX - 1), y0 + sy * i / (nY - 1)).
    float x0 = 0, y0 = 0, sx = 0, sy = 0;   // узел (j, i) → (x0 + sx·j/(nX−1), y0 + sy·i/(nY−1))
    ///@}
    /// Номер изменения размера сетки.
    quint64 gridVersion = 0;
    /// @name Слои сетки
    ///@{
    /// Слой поля и слой eps (или N, Y, B).
    GridLayer field, eps;
    ///@}

    // Цветная геометрия: топология, оси, размеры, курсор. Вершина — x, y, z, r, g, b, a.
    /// Цветные треугольники (топология, стрелки, метка точки): по 7 чисел на вершину.
    std::vector<float> triangles;
    /// Цветные отрезки (контуры, оси, размеры): по 7 чисел на вершину.
    std::vector<float> lines;
    /// Номер изменения цветной геометрии.
    quint64 geometryVersion = 0;

    // Габариты сцены для подбора расстояния камеры.
    /// @name Габариты сцены
    ///@{
    /// Размеры сцены по X, Y и половина высоты по Z — для подбора расстояния камеры.
    float boundX = 2.5f, boundY = 2.5f, boundZ = 1.0f;
    ///@}

    /// Надписи в точках сцены.
    std::vector<SceneLabel> labels;
    /// Номер изменения надписей (в коде модуля не увеличивается).
    quint64 labelsVersion = 0;
};

} // namespace fieldview
