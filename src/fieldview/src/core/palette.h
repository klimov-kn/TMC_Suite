// Цветовые шкалы FieldView.
//
//   «Волна»    — знакопеременные величины (поле в такт): −max фиолетовый, 0 тёмный, +max циан;
//   «Свечение» — неотрицательные (|E|, амплитуда, ε, N, Y, B);
//   «20 цветов» — пользовательская шкала из 20 цветов уровней, как в Windows-версии
//   (окно «Цвета уровней»; по умолчанию — исходные цвета FieldView 4.1).
//
// «Волна» и «Свечение» — опорные цвета из оформления пакета (style-guide), между ними —
// линейная интерполяция в OKLab: светлота растёт монотонно, картинка читается и без цвета.
/// @file palette.h
/// @brief Цветовые шкалы FieldView («Волна», «Свечение», 20 цветов уровней) и цвета материалов топологии.
///
/// Часть модуля FieldView (слой `core`). Шкала превращает нормированное значение
/// t из [0, 1] в цвет; для видеокарты шкала записывается текстурой 256 x 1.
/// @see https://www.tamic.ru/docs/code/fieldview.html#palettes
#pragma once

#include <QColor>
#include <QImage>
#include <QVector>

#include <array>

namespace fieldview {

/// @brief Вид цветовой шкалы слоя.
///
/// `Auto` — выбрать по данным («Волна» для знакопеременных, «Свечение» для неотрицательных;
/// у слоя eps — всегда «Свечение»); `Wave` — «Волна»; `Glow` — «Свечение»; `Custom` — 20
/// цветов уровней пользователя. Числа хранятся в настройках — менять нельзя.
enum class ScaleKind : int { Auto = 0, Wave = 1, Glow = 2, Custom = 3 };

/// Двадцать цветов уровней: индекс 0 — нижний уровень, 19 — верхний.
using Colors20 = std::array<QColor, 20>;

/// @brief Возвращает исходные 20 цветов уровней поля (FieldView 4.1).
///
/// Исходные 20 цветов поля Windows-версии (конструктор CFldViewView).
/// @return Цвета: синие — зелёные — красные — жёлтый — белый снизу вверх.
Colors20 classicFieldColors();
/// @brief Возвращает исходные 20 цветов уровней слоя eps (FieldView 4.1).
///
/// Исходные 20 цветов слоя ε Windows-версии.
/// @return Цвета от жёлтого (0) к циану (19).
Colors20 classicEpsColors();
/// @brief Возвращает 20 цветов, взятых из шкалы в точках t = i / 19.
///
/// 20 цветов, взятых равномерно из шкалы (для заполнения пользовательской шкалы).
/// @param[in] k  шкала (`Wave`, `Glow`; для `Custom` берутся исходные цвета поля)
/// @return Цвета уровней 0 … 19.
Colors20 sampleColors(ScaleKind k);

/// @brief Возвращает опорные цвета шкалы, равномерно расставленные по t от 0 до 1.
///
/// Опорные цвета шкалы «Волна» / «Свечение».
/// @param[in] k  `Glow` — 8 цветов «Свечения»; любое другое — 9 цветов «Волны»
/// @return Опорные цвета снизу вверх.
QVector<QColor> scaleStops(ScaleKind k);
/// @brief Возвращает цвет шкалы в точке t.
///
/// Цвет шкалы в точке t ∈ [0, 1]. Для Custom — кусочно-линейно по 20 цветам.
///
/// «Волна» и «Свечение» — линейная интерполяция между соседними опорными цветами в
/// пространстве OKLab; `Custom` — линейно по каналам sRGB между соседними из 20 цветов.
/// @param[in] k       шкала (`Auto` здесь равносильна «Волне»)
/// @param[in] t       положение на шкале, 0 — низ, 1 — верх; выход за [0, 1] обрезается
/// @param[in] custom  20 цветов для `Custom`
/// @return Цвет sRGB.
QColor scaleColor(ScaleKind k, double t, const Colors20 &custom);
/// @brief Строит картинку шкалы шириной `width` и высотой 1 точка (формат RGBA8888).
///
/// Текстура W×1 RGBA8 для видеокарты.
/// @param[in] k       шкала
/// @param[in] custom  20 цветов для `Custom`
/// @param[in] width   число точек, не меньше 2; точка x соответствует t = x / (width - 1)
/// @return Картинка для текстуры шкалы.
QImage scaleImage(ScaleKind k, const Colors20 &custom, int width = 256);

/// @brief Возвращает цвет материала топологии по умолчанию.
///
/// Цвета материалов топологии по умолчанию (оформление пакета):
/// 0 — ε, 1 — металл, 2 — магнитная стенка, 3 — вход (порт), 4 — поглотитель, 5 — плазма.
/// @param[in] slot  0 — eps, 1 — металл, 2 — магнитная стенка, 3 — вход, 4 — поглотитель, 5 — плазма
/// @return Цвет; для неизвестного номера — цвет диэлектрика.
QColor defaultTopologyColor(int slot);

} // namespace fieldview
