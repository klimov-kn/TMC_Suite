// GifWriter — анимированный GIF из кадров QImage (экспорт анимации поля, «Поделиться»).
//
// Свой кодировщик (GIF89a, LZW), без сторонних библиотек: в Qt записи GIF нет. У каждого
// кадра своя палитра — 256 самых частых цветов кадра (цвета сводятся к 5-6-5 бит, затем
// каждому цвету кадра — ближайший из палитры). Шкалы поля плавные, поэтому этого
// хватает; переходы без сглаживания (dither) — анимация не «шумит».
/// @file gifwriter.h
/// @brief Запись анимированного GIF (GIF89a, LZW) из последовательности картинок.
///
/// Часть модуля FieldView (слой `core`). Используется экспортом анимации тактов.
/// @see https://www.tamic.ru/docs/code/fieldview.html#gif
#pragma once

#include <QFile>
#include <QImage>
#include <QString>

namespace fieldview {

/// @brief Кодировщик анимированного GIF: открыть, добавить кадры, закрыть.
///
/// Логический экран — `width x height` без общей палитры; у каждого кадра своя палитра
/// из 256 самых частых цветов (после сведения к 5-6-5 бит), без сглаживания; анимация
/// повторяется бесконечно (блок NETSCAPE2.0). Не потокобезопасен; один объект — один файл.
/// @see https://www.tamic.ru/docs/code/fieldview.html#gif
class GifWriter
{
public:
    /// @brief Создаёт файл и пишет заголовок GIF.
    ///
    /// Открыть файл; width×height — размер всех кадров (другие масштабируются).
    /// @param[in] path    путь к файлу `.gif` (перезаписывается)
    /// @param[in] width   ширина кадров, точек (1 … 65535)
    /// @param[in] height  высота кадров, точек (1 … 65535)
    /// @return `false` — файл не создан или не записан (текст — `error()`).
    bool open(const QString &path, int width, int height);
    /// @brief Кодирует и дописывает кадр.
    ///
    /// Добавить кадр; delayCs — показ кадра, сотые секунды.
    /// @param[in] image    кадр; другой размер масштабируется до размера `open()`
    /// @param[in] delayCs  время показа кадра, сотые доли секунды (не меньше 1)
    /// @return `false` — ошибка записи (текст — `error()`).
    bool addFrame(const QImage &image, int delayCs);
    /// @brief Дописывает завершающий байт и закрывает файл.
    ///
    /// Дописать конец файла. false — ошибка записи.
    /// @return `false` — файл не был открыт или произошла ошибка записи.
    bool close();
    /// @brief Возвращает текст последней ошибки файла.
    /// @return Текст ошибки (пусто — ошибок не было).
    QString error() const { return m_error; }

private:
    /// @brief Сжимает индексы точек кадра кодом LZW и пишет их подблоками по 255 байт.
    /// @param[in] indices  номера цветов палитры, по байту на точку, строка за строкой
    void writeLzw(const QByteArray &indices);

    /// Выходной файл.
    QFile m_file;
    /// @name Размер кадров, точек
    ///@{
    /// Ширина и высота логического экрана GIF.
    int m_w = 0, m_h = 0;
    ///@}
    /// Текст последней ошибки.
    QString m_error;
};

} // namespace fieldview
