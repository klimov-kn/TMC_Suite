/// @brief Подставляет макрос `mac` во все его вызовы в тексте после текущей позиции.
///
/// Вызов имеет вид `имя п1; п2; ...;` — после имени один символ-разделитель (обычно
/// пробел), каждый фактический параметр заканчивается `;`. Вызов заменяется телом, где
/// на месте формальных параметров стоят фактические. Подставленный текст просматривается
/// повторно, поэтому макрос, вызывающий сам себя, переполняет буфер.
/// @param[in,out] buf  буфер; `inp_p` на входе — место бывшего `#define`
/// @param[in,out] mac  разобранный макрос; `m[1..j1]` перезаписываются фактическими параметрами
/// @return `BUF_NULL` — успех; `BUF_ERROR_FACT_PARAM` — не хватает параметра или `;`;
///         `BUF_EOF` — буфер переполнен; `-1` — нет памяти.
/// @see https://www.tamic.ru/docs/code/lib-prepr.html#macro-call
int  def_subst_mac( BUFFER  *buf, MACROS  *mac);
/// @brief Разрезает тело макроса (текст после `@`) на фрагменты между вхождениями формальных параметров.
///
/// Тело разбивается на лексемы (`def_gets`); лексема, совпадающая с именем формального
/// параметра, удаляется из текста, а следующий за ней фрагмент получает в `im1` номер
/// этого параметра. Заполняет `m1`, `im1`, `i2`.
/// @param[in]     buf  буфер (не используется)
/// @param[in,out] mac  макрос после `def_separ_mac_name()`; `mac` перестраивается на месте
/// @param[in]     i    индекс символа `@` в `mac->mac`
/// @return Индекс конца тела (`>= 0`); `-1` — нет памяти или фрагментов больше `BUF_MASKA_MAX`.
int  def_set_formal_param( BUFFER  *buf, MACROS  *mac, int i);
/// @brief Выделяет из текста `#define` имя макроса и формальные параметры (до разделителя `@`).
///
/// Формат: `#define имя п1; п2; ...; @тело`. Имя отделяется пробелом или табуляцией,
/// каждый параметр завершается `;`; без параметров — `#define имя @тело` или `#define имя@тело`.
/// Заполняет `m[0]`, `m[1..j1]`, `j1`.
/// @param[in]     buf  буфер (проверяется только `inp_p >= 0`)
/// @param[in,out] mac  `mac->mac` — текст директивы; имя и параметры записываются на место
/// @return Индекс символа `@` в `mac->mac` (`> 0`); `BUF_ERROR_NO_SEP` — нет `@` или
///         пустое имя; `BUF_ERROR_NO_FORMAL_PARAM` — ошибка в списке параметров;
///         `-1` — параметров больше 58.
/// @see https://www.tamic.ru/docs/code/lib-prepr.html#define
int  def_separ_mac_name( BUFFER  *buf, MACROS  *mac);
/// @brief Проверяет, что ни одно имя макроса не определено дважды.
///
/// Собирает имена всех `#define`, сортирует их и находит первое (по тексту) определение,
/// имя которого повторяется ниже.
/// @param[in,out] buf  буфер; `inp_p` после вызова не восстанавливается
/// @return `BUF_NULL` — повторов нет; `BUF_ERROR_REDEC` — найден повтор (текст
///         «`Redefined <имя>`»); `-1` — ошибка разбора `#define` или нехватка памяти.
/// @see https://www.tamic.ru/docs/code/lib-prepr.html#redefine
int  def_err_dec( BUFFER  *buf );

