/// @file Error1.h
/// @brief Числовые коды ошибок пакета (наследие TAMIC) и функции вывода сообщений об ошибках.
///
/// Коды сгруппированы по тысячам: 0xxx/1xxx — память, 2xxx — файлы, S-матрицы,
/// выражения, препроцессор; 3xxx — DOS; 4xxx — диски и пути; 5xxx — разбор задания и
/// модели; 6xxx — база данных и связи блоков; 7xxx/8xxx — прочее. Код передаётся в
/// `put_error_messege(int, ...)`. В Qt6-версии эта функция (sfile95, errors.cpp) —
/// заглушка: ничего не выводит и возвращает 0, поэтому коды служат лишь метками в коде.
/// Ошибки ядер передаются текстом через `CTmcLibError` (tmcliberror.h).
/// Блоки под `_MODEL_E`, `_MODEL_H`, `_MODEL_IC`, `_MODEL_M` в сборке не активны:
/// эти макросы не определяются.
/// @see https://www.tamic.ru/docs/code/shared-headers.html#error-codes

/// Не хватает памяти для работы программы (фатальная ошибка; выдаёт `alloc_mem_err`).
#define FATAL_MEM_ALLOC_ERROR      0001


/// Не открывается файл листинга.
#define ERROR_OPEN_LISTING         2005


                               /* TWP-file  error codes*/


             /* S-matrix file error codes */
/// Ошибка записи файла S-матрицы.
#define ERROR_WRITE_S              2300
/// Ошибка чтения файла S-матрицы.
#define ERROR_READ_S               2301
/// Не открывается файл S-матрицы.
#define ERROR_OPEN_S               2305
/// Файл не является файлом S-матрицы (нет метки формата).
#define SMT_LABEL_ERROR            2306
/// Устаревшая версия файла S-матрицы.
#define SMT_VERSION_ERROR          2307
/// Не хватает памяти для всех частот S-матрицы; обработана только часть.
#define SMT_FRQ_MEMORY             2309

                                /* expression error codes*/

                                /* Preprocessor error codes*/





