#define BAD_NF_PARM                5104
















/// @brief Сообщает об ошибке по числовому коду (`printf`-подобные аргументы — к тексту).
///
/// Определена в sfile95 (errors.cpp) как заглушка: тело закомментировано, функция
/// ничего не выводит и всегда возвращает 0.
/// @param[in] err_num  код ошибки из этого файла
/// @param[in] ...      аргументы для текста сообщения (не используются)
/// @return 0.
/// @warning Ошибки, переданные только через эту функцию, в Qt6-версии не видны
/// пользователю; вызывающий код должен сам проверять возвращаемые значения.
int put_error_messege( int err_num, ... );
/// @brief Запоминает текст ошибки препроцессора.
///
/// Определена в prepr (prep_mn.cpp): копирует текст в буфер ошибки препроцессора
/// `szError` (буфер передаёт вызывающий препроцессор код). Длина текста должна быть
/// меньше размера этого буфера.
/// @param[in] ch  текст ошибки, оканчивающийся нулём
/// @return 0.
/// @note Вьюверы имеют собственный одноимённый метод `CTMCGROUTDoc::put_error_messege`.
/// @see https://www.tamic.ru/docs/code/lib-prepr.html#errors
int put_error_messege( const char *ch );



