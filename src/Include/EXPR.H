/// @file EXPR.H
/// @brief Вычислитель арифметических выражений (библиотека `exprint`, часть Expr) и его коды ошибок.
///
/// Строка вида `2*sin(x)+1.5e-3` вычисляется рекурсивным разбором: присваивание,
/// сложение/вычитание, умножение/деление, степень, скобки, функции, числа и
/// однобуквенные переменные. Здесь же объявлены функции интерпретатора (часть Inter:
/// операторы `;`, `return`, `if`, `while`) и контекст потока для параллельного
/// вычисления выражений. Используется ядрами (eps, N, B, sigma и сигналы порта,
/// заданные формулами в .tpl), библиотекой TMCIndan и вьюверами.
/// @warning Защиты от повторного включения нет: подключение в один файл и expr.h,
/// и inter.h (который сам включает expr.h) даёт ошибку компиляции «conflicting
/// declaration EXPR_THREAD_CTX». Включайте только один из двух заголовков.
/// @see https://www.tamic.ru/docs/code/lib-expr.html

/// @name Коды встроенных функций
/// Номер функции в таблице `fun[]` (expr_in1.cpp) и код операции для `expr_comp`.
/// Код 6 зарезервирован (заглушка «1111»). Коды бинарных операций — символы
/// `'='`, `'+'`, `'-'`, `'*'`, `'/'`, `'^'` (все они больше `LOG10`).
/// @{
/** Код встроенной функции; имя функции в выражении — имя макроса строчными буквами. */
#define ABS    0
#define EXP    1
#define LOG    2
#define SIN    3
#define COS    4
#define TAN    5
#define SQRT   7
#define SINH   8
#define COSH   9
#define TANH  10
#define ASIN  11
#define ACOS  12
#define ATAN  13
#define LOG10 14
/// @}

/// Аргумент `expr_set_angle`: тригонометрические функции работают в радианах.
#define EXPR_RADIAN        1
/// Аргумент `expr_set_angle`: тригонометрические функции работают в градусах
/// (режим по умолчанию при запуске программы).
#define EXPR_GRADUS        0

/// Наибольший допустимый модуль аргумента `sin`, `cos`, `tan` (в единицах угла);
/// при превышении — ошибка с кодом `-SIN`, `-COS`, `-TAN`.
#define FLT_MAX_SIN 65536.


/// @name Коды ошибок вычислителя
/// Отрицательные числа, хранятся через `expr_set_error_cod`. Кроме перечисленных,
/// ошибка функции даёт код `-<код функции>` (например, `-LOG` — логарифм от числа <= 0).
/// Текст по коду возвращает `expr_get_error`. 0 — ошибки нет.
/// @{

/// Непарные круглые скобки.
#define ERROR_BRACKET      -17
/// Строка не распознана: не число, не переменная, не выражение и не известная функция.
#define ERROR_FUNCTION     -18
/// Степень `x^y` не определена: `x < 0` с дробным `y` или `0^y` при `y <= 0`.
#define ERROR_POW          -16
/// Деление на ноль; возвращается `FLT_MAX`.
#define ERROR_DIV_0        -15
/// Неверное выражение (пустой операнд, `()`, больше 10 000 000 итераций `while`).
#define ERROR_EXPRESSION   -19
/// Результат больше `FLT_MAX`; возвращается `FLT_MAX`.
#define ERROR_OVERFLOW     -20
/// Не ошибка, а признак выполненного `return(...)` интерпретатора: прерывает разбор,
/// значение берётся из `inte_get_inter_value`.
#define ERROR_RETURN       -21
/// Слева от `=` стоит не однобуквенная переменная.
#define ERROR_VAR          -22
/// @}

/// @brief Задаёт единицы угла для `sin`, `cos`, `tan`, `asin`, `acos`, `atan`.
/// @param[in] flag  `EXPR_GRADUS` — градусы; любое другое значение — радианы
/// @note Настройка общая для всех потоков (в контекст потока не входит). Ядра ставят
/// радианы или градусы по единицам угла из задания (библиотека TMCIndan).
void    expr_set_angle( int flag );
/// @brief Выполняет одну операцию над двумя подстроками-операндами.
///
/// Левый операнд вычисляется всегда (`n1 == 0` — считается нулём, так получается
/// унарный минус), правый — только для бинарных операций (`cod > LOG10`). Для `'='`
/// значение правого операнда присваивается переменной, имя которой — левый операнд.
/// Результаты больше `FLT_MAX` считаются переполнением.
/// @param[in] cod    код функции (`ABS` … `LOG10`) или символ операции `= + - * / ^`
/// @param[in] oper1  начало левого операнда (для функции — её аргумент со скобками)
/// @param[in] n1     длина левого операнда, символов
/// @param[in] oper2  начало правого операнда
/// @param[in] n2     длина правого операнда, символов
/// @return Значение; при ошибке 0 или `FLT_MAX`, код ошибки установлен.
/// @warning Если код ошибки уже ненулевой, сразу возвращает 0.
/// @see https://www.tamic.ru/docs/code/lib-expr.html#operations
_real   expr_comp( int cod, char   *oper1, int n1, char  *oper2, int n2 );
/// @brief Устанавливает код ошибки вычислителя (в контексте потока, если он привязан).
/// @param[in] n  0 — сбросить; иначе одна из констант `ERROR_*` или `-<код функции>`
void    expr_set_error_cod( int n );
/// @brief Возвращает текущий код ошибки вычислителя (контекста потока или общий).
/// @return 0 — ошибки нет; иначе отрицательный код.
int     expr_get_error_cod( void );
/// @brief Рекурсивно вычисляет подстроку `lex[0..n)`.
///
/// Порядок распознавания: число (`expr_numbern`), переменная (`expr_is_per`), операция
/// вне скобок в порядке `= + - * / ^` (самая правая; для `^` — самая левая, поэтому
/// `a^b^c = a^(b^c)`), выражение в скобках, функция.
/// @param[in,out] lex  начало подстроки; символы `lex[n]`, `lex[4]`, `lex[5]`, `lex[6]`
///                     временно заменяются нулём и восстанавливаются
/// @param[in]     n    длина подстроки, символов
/// @return Значение; при ошибке 0 (или `FLT_MAX`), код ошибки установлен.
/// @see https://www.tamic.ru/docs/code/lib-expr.html#grammar
_real   expr_inter( char  *lex, int n );
/// @brief Проверяет, является ли подстрока числом (`-12`, `0.5`, `1.24e+17`, `1e18`).
/// @param[in] lex  начало подстроки
/// @param[in] n    длина, символов; строки длиннее 40 символов числом не считаются
/// @return 0 — число; 1 — не число.
int     expr_numbern( char *lex, int n);
/// @brief Возвращает значение переменной по первому символу имени.
/// @param[in] lpszName     имя (используется только первый символ)
/// @param[in] nLenghtName  длина имени (не используется)
/// @return Значение из контекста потока, если он привязан, иначе из общей таблицы;
///         не присвоенная переменная равна 0.
_real   expr_get_per( char   *lpszName, int nLenghtName );
/// @brief Присваивает значение переменной по первому символу имени.
/// @param[in] lpszName     имя (используется только первый символ)
/// @param[in] nLenghtName  длина имени (не используется)
/// @param[in] rValue       новое значение
/// @note Пишет в контекст потока, если он привязан, иначе в общую таблицу.
void    expr_set_per( char   *lpszName, int nLenghtName, _real rValue );
/// @brief Проверяет, является ли подстрока именем переменной (одна латинская буква).
/// @param[in] lpszName     начало подстроки
/// @param[in] nLenghtName  длина подстроки, символов
/// @return 0 — переменная (`A`–`Z`, `a`–`z`, регистр различается); -1 — нет.
int     expr_is_per( char   *lpszName, int nLenghtName );
/// @brief Возвращает английский текст текущей ошибки вычислителя.
/// @return Указатель на статическую строку («all right» при коде 0,
///         «unknown error of expression» при неизвестном коде). Не освобождать.
const char   *expr_get_error( void );
/// @brief Удаляет пробельные символы из строки и выполняет её интерпретатором (`inte_atof`).
///
/// Основная точка входа для ядер: формулы eps, N, B, sigma, сигналов порта.
/// @param[in,out] string  программа интерпретатора; пробелы, табуляции и переводы строк
///                        удаляются на месте
/// @param[out]    r       результат
/// @return Код ошибки вычислителя: 0 — успех.
/// @see https://www.tamic.ru/docs/code/lib-inter.html
int     i1nte_atof_1( char *string, double *r );
/// @brief Сбрасывает код ошибки и выполняет программу интерпретатора.
/// @param[in,out] string  текст программы без пробелов (временно изменяется при разборе)
/// @return Значение последнего оператора или значение `return(...)`; признак ошибки —
///         `expr_get_error_cod() != 0`.
_real   inte_atof( char  *string );
/// @brief Выполняет подстроку программы: последовательность через `;`, блок `{...}`,
/// выражение или оператор.
/// @param[in,out] lex  начало подстроки
/// @param[in]     n    длина, символов
/// @return Значение последнего выполненного оператора; 0 при ошибке.
_real   inte_inter( char  *lex, int n );
/// @brief Выполняет оператор `return(e)`, `if(c){...}` или `while(c){...}`.
/// @param[in,out] lex  начало оператора
/// @param[in]     n    длина, символов
/// @return Значение оператора; если строка — не оператор, ставит код `ERROR_FUNCTION`.
/// @see https://www.tamic.ru/docs/code/lib-inter.html#operators
_real   inte_oper( char   *lex, int n );
/// @brief Находит закрывающую круглую скобку условия `if(`/`while(`.
/// @param[in] lex  текст сразу после открывающей скобки
/// @param[in] n    длина текста, символов
/// @return Позиция парной `)` относительно `lex`; `n`, если не найдена.
int     inte_select_blanck( char   *lex, int n );
/// @brief Запоминает значение, возвращённое `return(...)` (в контексте потока или общее).
/// @param[in] r  значение
void    inte_set_inter_value( _real r );
/// @brief Возвращает значение, запомненное `inte_set_inter_value`.
/// @return Значение последнего `return(...)`.
_real   inte_get_inter_value( void );

// EPSFAST: per thread interpreter context. While a thread has a context bound,
// the interpreter keeps its variables, error code and return value there
// instead of in the common (static) ones, so several threads can evaluate
// expressions at once. begin copies the common variables into the context.
/// @brief Контекст интерпретатора для одного потока.
///
/// Пока контекст привязан к потоку (`expr_thread_ctx_begin`), переменные, код ошибки
/// и значение `return` хранятся в нём, а не в общих статических переменных, и потоки
/// не мешают друг другу. Память выделяет вызывающий (обычно на стеке потока).
/// @see https://www.tamic.ru/docs/code/lib-expr.html#threads
typedef struct {
	/// Значения переменных, индекс — код символа имени.
	_real rPer[256];
	/// Код ошибки вычислителя (0 — ошибки нет).
	int   nErrorCod;
	/// Значение последнего `return(...)`.
	_real rInterValue;
} EXPR_THREAD_CTX;
/// @brief Возвращает контекст, привязанный к текущему потоку.
/// @return Указатель на контекст или NULL, если поток работает с общими переменными.
EXPR_THREAD_CTX *expr_get_thread_ctx( void );
/// @brief Привязывает контекст к текущему потоку.
///
/// Копирует в контекст текущие общие переменные, сбрасывает код ошибки и значение
/// `return`. До `expr_thread_ctx_end` все вызовы библиотеки в этом потоке работают
/// с контекстом.
/// @param[in,out] pCtx  контекст; должен существовать до `expr_thread_ctx_end`
void    expr_thread_ctx_begin( EXPR_THREAD_CTX *pCtx );
/// @brief Отвязывает контекст от текущего потока; поток возвращается к общим переменным.
void    expr_thread_ctx_end( void );
