// CTMCGrExpression window
/// @file TMCGrExpression.h
/// @brief Кривая-выражение вьюверов: формула над несколькими файлами `.s` (или сигналами), вычисляемая по точкам.
///
/// Общий заголовок трёх вьюверов (TMCGROUT, TMCROS, TMC_DN); у каждой программы своя
/// реализация `tmcgrexpression.cpp` в каталоге вьювера. Строка графика в файле документа
/// вида `{ ... [файл1] ... [файл2] ... }` превращается в объект `CTMCGrExpression`:
/// имена в квадратных скобках — файлы с данными, текст между ними — формула библиотеки
/// выражений (Inter/Expr). Значение в точке получается подстановкой чисел вместо имён.
/// @see https://www.tamic.ru/docs/code/tmcgrout.html#expressions
#ifndef _TMC_GR_EXPRESSION_1
#define _TMC_GR_EXPRESSION_1

#include <Typedef.h>

// D-8: unwrapping of the phase in GetCPhase: 0 - the phase decreases monotonically (Foster, the default, as before),
// 1 - the standard unwrapping with the threshold pi. One per program, set by the menu Config.
/// Способ разворота фазы в кривых-выражениях (`GetCPhase`): 0 — фаза только убывает
/// (каждый скачок вверх считается переходом через -2*pi; по умолчанию), 1 — стандартный
/// разворот с порогом pi. Одна переменная на программу; задаётся пунктом меню Config
/// главного окна и хранится в настройках программы (`Settings/PhaseUnwrap`).
/// Определена в `tmcgrexpression.cpp` каждого вьювера.
/// @see https://www.tamic.ru/docs/theory/smatrix.html#phase
extern int g_nTmcPhaseUnwrap;

/// @brief Кривая-выражение: разбор формулы с именами файлов, хранение их данных и вычисление по точкам.
///
/// Создаётся документом вьювера при чтении строки графика, начинающейся с `{` и
/// оканчивающейся на `}` (`CTMCGROUTDoc::ReadGraph1Expession`); указатель хранится в
/// `TMC_GR_DOC1::pcExpr`, удаляется документом вместе со списком графиков
/// (`DocFileDelData`). Порядок работы: конструктор запоминает строку, `InitData` делит
/// её на части и выделяет массивы, документ читает каждый файл в массивы, которые
/// отдают `GetNPoint`/`GetFreqArray`/`GetSMatrArray`, затем вид вызывает один из
/// методов `GetExpressionValue*` для каждой точки. Объект владеет всеми массивами.
/// Значение каждого файла в точке сначала переводится в величину оси Y (КСВ, дБ, |S|,
/// фаза), затем подставляется в формулу; переменная `f` формулы — частота точки, Гц.
/// @note Потоки: только главный поток (библиотека выражений хранит переменные глобально).
/// @see https://www.tamic.ru/docs/code/tmcgrout.html#expressions
class CTMCGrExpression  
{
// Construction
public:
	/// @brief Вычисляет выражение в точке, подставляя КСВ каждого файла: (1+|S|)/(1-|S|).
	///
	/// При |S|, отличающемся от 1 меньше чем на 1e-4, |S| заменяется на 0.9999 (КСВ ~ 19999).
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения (безразмерное); 0 — объект не готов, номер вне диапазона
	///         или ошибка вычисления в этой точке.
	/// @see https://www.tamic.ru/docs/code/tmcgrout.html#graph-types
	double GetExpressionValueK( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя потери каждого файла L = -20*lg|S|, дБ.
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения, дБ (если формула линейна по L); 0 — объект не готов,
	///         номер вне диапазона или ошибка вычисления.
	double GetExpressionValueL( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя модуль |S| каждого файла.
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения (безразмерное); 0 — объект не готов, номер вне диапазона
	///         или ошибка вычисления.
	double GetExpressionValueSM( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя развёрнутую фазу S каждого файла, радианы.
	///
	/// Фаза разворачивается по частоте от первой точки до `nPoint` способом, заданным
	/// `g_nTmcPhaseUnwrap` (см. `GetCPhase`).
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения, радианы (если формула линейна по фазе); 0 — объект не
	///         готов, номер вне диапазона или ошибка вычисления.
	/// @see https://www.tamic.ru/docs/theory/smatrix.html#phase
	double GetExpressionValueSFR( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя развёрнутую фазу S каждого файла, градусы.
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения, градусы (если формула линейна по фазе); 0 — объект не
	///         готов, номер вне диапазона или ошибка вычисления.
	/// @see https://www.tamic.ru/docs/theory/smatrix.html#phase
	double GetExpressionValueSFD( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя фазу S каждого файла без разворота, радианы.
	///
	/// Вызывается видом вместо `GetExpressionValueSFR`, когда по оси X выбраны единицы
	/// пользователя (`TMC_GR_TYPE_F_USER`). Фаза — `cphase`, диапазон (-2*pi, 0].
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения, радианы; 0 — объект не готов, номер вне диапазона или
	///         ошибка вычисления.
	double GetExpressionValueSFR_User( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя фазу S каждого файла без разворота, градусы.
	///
	/// Вариант `GetExpressionValueSFD` для единиц пользователя по оси X; фаза в (-360, 0].
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Значение выражения, градусы; 0 — объект не готов, номер вне диапазона или
	///         ошибка вычисления.
	double GetExpressionValueSFD_User( int nPoint );
	/// @brief Присваивает переменной `f` библиотеки выражений частоту точки (Гц) и возвращает её.
	///
	/// Вычисляет программу `{f=(частота)}` с частотой из массива первого файла. Вызывается
	/// в начале каждого `GetExpressionValue*`, поэтому в формуле можно использовать `f`.
	/// @param[in] nPoint номер частотной точки, 0..число точек первого файла
	/// @return Частота точки, Гц; 0 — объект не готов, номер вне диапазона или ошибка.
	double GetExpressionValue( int nPoint );
	/// @brief Вычисляет выражение в точке, подставляя действительную часть данных каждого файла.
	///
	/// Используется только TMCROS (выражения над временными сигналами, где в массиве
	/// данных лежат значения сигнала); определён в `viewers/tmcrtout/tmcgrexpression.cpp`.
	/// В TMCGROUT не определён и не вызывается.
	/// @param[in] nPoint номер точки (отсчёта времени)
	/// @return Значение выражения; 0 — объект не готов, номер вне диапазона или ошибка.
	double GetExpressionValueRe( int nPoint );	// A-28: TMCROS - vyrazhenie ot znachenii signalov
	/// @brief Проверяет, что у всех файлов выражения одинаковые частоты.
	///
	/// Сравнивает число точек и каждую частоту с первым файлом (относительное расхождение
	/// не более 1e-15). Вызывается документом после чтения всех файлов.
	/// @return TRUE — частоты совпадают; FALSE — различаются (кривая не строится,
	///         в подписи `Error_expression_different_freq_array_...`).
	BOOL IsFreqCorrect( void );
	/// @brief Возвращает адрес счётчика точек файла с номером `nFileName` (заполняет документ).
	/// @param[in] nFileName номер файла в выражении, 0..`GetNVar()`-1
	/// @return Адрес элемента массива числа точек; NULL — номер вне диапазона или массив не создан.
	int * GetNPoint( int nFileName );
	/// @brief Возвращает адрес указателя на массив элементов S файла `nFileName` (заполняет документ).
	///
	/// Массив выделяет `read_S_matrix_element` библиотеки sfile95, освобождает деструктор.
	/// @param[in] nFileName номер файла в выражении, 0..`GetNVar()`-1
	/// @return Адрес указателя; NULL — номер вне диапазона или массив не создан.
	_complex ** GetSMatrArray( int nFileName );
	/// @brief Возвращает адрес указателя на массив частот файла `nFileName`, Гц (заполняет документ).
	/// @param[in] nFileName номер файла в выражении, 0..`GetNVar()`-1
	/// @return Адрес указателя; NULL — номер вне диапазона или массив не создан.
	double ** GetFreqArray( int nFileName );
	/// @brief Возвращает имя файла с номером `nFileName` — текст между квадратными скобками.
	///
	/// Имя может начинаться с `*вход1;мода1;вход2;мода2*` (выбор элемента S-матрицы).
	/// @param[in] nFileName номер файла в выражении, 0..`GetNVar()`-1
	/// @return Строка, принадлежащая объекту; NULL — номер вне диапазона.
	char * GetFileName( int nFileName );
	/// @brief Возвращает число файлов (пар квадратных скобок верхнего уровня) в выражении.
	/// @return Число файлов; 0 — до `InitData` или при ошибке разбора.
	int GetNVar( void );
	/// @brief Делит выражение на части и выделяет массивы под данные файлов.
	///
	/// Подсчитывает пары `[...]` верхнего уровня, создаёт массивы имён, частей формулы,
	/// счётчиков точек, частот и элементов S. При ошибке память освобождается.
	/// @return NULL — успех; иначе строка-константа с причиной: `Bad_Nvar_or_Bad_Bracket[]`
	///         (нет скобок или они непарные), `memory_allocation_error`, `init_data_error`.
	const char * InitData( void );
	/// @brief Запоминает текст выражения; массивы не создаются до `InitData`.
	/// @param[in] szExpression строка графика целиком, вместе с внешними `{` и `}`
	CTMCGrExpression( char *szExpression );

// Attributes
public:

// Operations
public:

// Implementation
public:
	/// @brief Освобождает все массивы объекта (`DeleteData`).
	virtual ~CTMCGrExpression();

	// Generated message map functions
protected:

private:
	/// @brief Возвращает фазу S файла `i` в точке без разворота, радианы, (-2*pi, 0].
	/// @param[in] i      номер файла в выражении
	/// @param[in] nPoint номер частотной точки
	/// @return Фаза, радианы; 0 — объект не готов или номер вне диапазона.
	double GetCPhase_User( int i, int nPoint );
	/// @brief Возвращает развёрнутую по частоте фазу S файла `i` в точке `nPoint`, радианы.
	///
	/// Проходит точки 1..`nPoint` и считает число переходов `n`: при `g_nTmcPhaseUnwrap` = 0
	/// каждый рост фазы между соседними точками — переход (фаза считается убывающей),
	/// при 1 — скачок больше pi вверх (+1) или вниз (-1). Результат: phi(nPoint) - 2*pi*n.
	/// @param[in] i      номер файла в выражении
	/// @param[in] nPoint номер частотной точки
	/// @return Фаза, радианы; 0 — объект не готов или номер вне диапазона.
	/// @see https://www.tamic.ru/docs/theory/smatrix.html#phase
	double GetCPhase( int i, int nPoint );
	/// Флаг ошибки объекта: TRUE — все вычисления возвращают 0. В коде вьювера в TRUE не устанавливается; сбрасывается в `DeleteData`.
	BOOL IsError;
	/// Число точек каждого файла, длина `nVar`; заполняет документ.
	int * pnPoint;
	/// Массивы элементов S каждого файла (комплексные, безразмерные), длина `nVar`.
	_complex ** ppcSmatrix;
	/// Массивы частот каждого файла, Гц, длина `nVar`.
	double ** ppdFreq;
	/// @brief Освобождает все массивы и обнуляет счётчики; объект возвращается в состояние до `InitData`.
	void DeleteData( void );
	/// @brief Делит строку на части формулы (`pszMaska`) и имена файлов (`pszVar`).
	///
	/// Части формулы — текст вне скобок верхнего уровня, их на одну больше, чем файлов:
	/// первая начинается с `{`, последняя оканчивается на `}`.
	/// @return TRUE — успех; FALSE — не хватило памяти.
	BOOL Init1Data( void );
	/// @brief Считает пары квадратных скобок верхнего уровня и записывает число в `nVar`.
	/// @return Число файлов; 0 — скобок нет, лишняя `]` или незакрытая `[`.
	int CalcNGraphExpession( void );
	/// Текст выражения целиком, с внешними фигурными скобками.
	CString csExpresion;
	/// Число частей формулы, `nVar` + 1.
	int nMaska;
	/// Число файлов в выражении.
	int nVar;
	/// Части формулы между именами файлов, длина `nMaska`; владеет объект.
	char ** pszMaska;
	/// Имена файлов (текст в квадратных скобках), длина `nVar`; владеет объект.
	char ** pszVar;
};

#endif

